"""Generates FlashMma, jitNN's tensor-core FlashAttention-2 for CUDA (KernelContext MMA, m16n8k16,
FP16 operands, FP32 accumulation) for head dimensions up to 128, one set of kernels per head size (32, 64, 128; smaller ones are
padded with zeros). Prints the Java class.

Forward: a work-group of 4 warps owns BQ = 64 query rows, 16 per warp; keys and values stream
through in tiles of BK = 64. Q, K and V are staged in shared memory in the blocked layouts the
fragment loads read (A: 16x16 FP16 blocks, row-major; B: 16x8 FP16 blocks, k-major). Per tile each
warp computes S = Q K^T for its 16 rows (8 accumulators of 16 x 8, 4 MMAs each), applies scale,
mask and causality to the accumulator registers, takes the row maximum through shared memory
(4 lanes share a row), writes P = exp(S - m) as FP16 into its own A blocks and adds P V into fresh
accumulators, which are folded into the running output in registers (the rescale by
exp(m_old - m_new) is applied there, as accumulators cannot be written). Row sums stay per lane
and are reduced once at the end. lse = m + log(l), as FlashTiled64.
"""
# head size -> (forward warps, keys per forward tile, backwardQ warps, keys per backwardQ tile,
# backwardKV warps, queries per backwardKV tile, reload A fragments per tile): 16 rows per warp,
# shared memory under 48 KB, and at 128 the fixed operands are re-read from shared memory each
# tile to keep register pressure down
VARIANTS = {32: (4, 64, 4, 32, 4, 32, False), 64: (4, 64, 4, 32, 4, 32, False), 128: (4, 32, 2, 32, 2, 16, True)}


def configure(d, warps, bk):
    global D, BQ, BK, KB, NB_S, KB_P, NB_O, THREADS, TB, NBT, KBT
    D, BQ, BK, THREADS = d, 16 * warps, bk, 32 * warps
    KB = D // 16      # k blocks over the head dimension
    NB_S = BK // 8    # n blocks of S (keys)
    KB_P = BK // 16   # k blocks of P (keys)
    NB_O = D // 8     # n blocks of O (head dimension)
    TB = bk           # streamed rows per tile in the backward kernels
    NBT = TB // 8
    KBT = TB // 16

o = []
w = o.append


def ind(n):
    return "    " * n


w("package ai.beestream.jitnn.kernels;")
w("")
w("import uk.ac.manchester.tornado.api.KernelContext;")
w("import uk.ac.manchester.tornado.api.enums.MMAShape;")
w("import uk.ac.manchester.tornado.api.math.TornadoMath;")
w("import uk.ac.manchester.tornado.api.types.HalfFloat;")
w("import uk.ac.manchester.tornado.api.types.arrays.FloatArray;")
w("import uk.ac.manchester.tornado.api.types.arrays.HalfFloatArray;")
w("import uk.ac.manchester.tornado.api.types.arrays.IntArray;")
w("")
w("/**")
w(" * Tensor-core FlashAttention-2 for CUDA (compute capability 8.0+) and head dimensions up to 128,")
w(" * generated by scripts/codegen/flash_mma.py: FP16 q, k and v, FP32 accumulation, operands")
w(" * addressed through the same meta strides as FlashKernels64. Same arguments and lse as")
w(" * FlashTiled64Half. One kernel set per head size ({@link #size}): forwardN, backwardQN and")
w(" * backwardKVN, with work-groups of 2 threads per row they own ({@link #forwardRows} queries,")
w(" * {@link #backwardQRows} queries, {@link #backwardKVRows} keys).")
w(" */")
w("public final class FlashMma {")
w("")
w("    /** Head dimensions up to this. */")
w("    public static final int D = 128;")
w("    private static final float MASKED = -3.0e38f;")
w("")
w("    /** The kernel set for head dimension d: 32, 64 or 128. */")
w("    public static int size(int d) {")
w("        return d <= 32 ? 32 : d <= 64 ? 64 : 128;")
w("    }")
w("")
for name, idx in (("forwardRows", 0), ("backwardQRows", 2), ("backwardKVRows", 4)):
    w("    /** Rows per work-group of the %s kernels for kernel set n; the work-group has twice as many threads. */" % name[:-4])
    w("    public static int %s(int n) {" % name)
    w("        return n == 32 ? %d : n == 64 ? %d : %d;" % tuple(16 * VARIANTS[n][idx] for n in (32, 64, 128)))
    w("    }")
    w("")
w("    private FlashMma() {")
w("    }")
w("")
w("    /** FP16 bits of a[i], or 0 when out of range. */")
w("    private static int bits(HalfFloatArray a, int i, boolean ok) {")
w("        int r = 0;")
w("        if (ok) {")
w("            r = a.get(i).getHalfFloatValue() & 0xFFFF;")
w("        }")
w("        return r;")
w("    }")
w("")
w("    /** a[i] rounded to FP16 bits, or 0 when out of range. */")
w("    private static int fbits(FloatArray a, int i, boolean ok) {")
w("        int r = 0;")
w("        if (ok) {")
w("            r = new HalfFloat(a.get(i)).getHalfFloatValue() & 0xFFFF;")
w("        }")
w("        return r;")
w("    }")
w("")
w("    /** Two FP32 values rounded to FP16 and packed (lo | hi << 16). */")
w("    private static int pack(float lo, float hi) {")
w("        return (new HalfFloat(lo).getHalfFloatValue() & 0xFFFF) | ((new HalfFloat(hi).getHalfFloatValue() & 0xFFFF) << 16);")
w("    }")
w("")



def get(arr, idx, ok, half):
    """FP16 bits of arr[idx] (FP32 arrays are rounded), 0 when not ok."""
    return ("bits(%s, %s, %s)" if half else "fbits(%s, %s, %s)") % (arr, idx, ok)


def stage_a(tile, arr, base, stride, first, limit, half, rows):
    """rows x D of arr (rows first .. first + rows of length d) into A blocks (k = head dimension)."""
    w(ind(2) + "for (int e = tid; e < %d; e += %d) {" % (rows * D // 2, THREADS))
    w(ind(3) + "int cp = e & 7;")
    w(ind(3) + "int r = (e >> 3) & 15;")
    w(ind(3) + "int blk = e >> 7;")
    w(ind(3) + "int rb = blk / %d;" % KB)
    w(ind(3) + "int kb = blk - rb * %d;" % KB)
    w(ind(3) + "int row = %s + rb * 16 + r;" % first)
    w(ind(3) + "int c = kb * 16 + cp * 2;")
    w(ind(3) + "int g = %s + row * %s + c;" % (base, stride))
    w(ind(3) + "%s[e] = %s | (%s << 16);" % (tile, get(arr, "g", "(row < %s) & (c < d)" % limit, half), get(arr, "g + 1", "(row < %s) & (c + 1 < d)" % limit, half)))
    w(ind(2) + "}")


def stage_bt(tile, arr, base, stride, first, limit, half, lvl):
    """TB rows of arr as B blocks with k = head dimension, n = row: ((kb * NB + nb) * 16 + kr) * 4 + np."""
    nbs = TB // 8
    w(ind(lvl) + "for (int e = tid; e < %d; e += %d) {" % (TB * D // 2, THREADS))
    w(ind(lvl + 1) + "int np = e & 3;")
    w(ind(lvl + 1) + "int kr = (e >> 2) & 15;")
    w(ind(lvl + 1) + "int blk = e >> 6;")
    w(ind(lvl + 1) + "int kb = blk / %d;" % nbs)
    w(ind(lvl + 1) + "int nb = blk - kb * %d;" % nbs)
    w(ind(lvl + 1) + "int j = %s + nb * 8 + np * 2;" % first)
    w(ind(lvl + 1) + "int c = kb * 16 + kr;")
    w(ind(lvl + 1) + "int g = %s + j * %s + c;" % (base, stride))
    w(ind(lvl + 1) + "%s[e] = %s | (%s << 16);" % (tile, get(arr, "g", "(j < %s) & (c < d)" % limit, half), get(arr, "g + " + stride, "(j + 1 < %s) & (c < d)" % limit, half)))
    w(ind(lvl) + "}")


def stage_b(tile, arr, base, stride, first, limit, half, lvl):
    """TB rows of arr as B blocks with k = row, n = head dimension: ((kb * 8 + nb) * 16 + kr) * 4 + np."""
    w(ind(lvl) + "for (int e = tid; e < %d; e += %d) {" % (TB * D // 2, THREADS))
    w(ind(lvl + 1) + "int np = e & 3;")
    w(ind(lvl + 1) + "int kr = (e >> 2) & 15;")
    w(ind(lvl + 1) + "int blk = e >> 6;")
    w(ind(lvl + 1) + "int kb = blk / %d;" % NB_O)
    w(ind(lvl + 1) + "int nb = blk - kb * %d;" % NB_O)
    w(ind(lvl + 1) + "int j = %s + kb * 16 + kr;" % first)
    w(ind(lvl + 1) + "int c = nb * 8 + np * 2;")
    w(ind(lvl + 1) + "int g = %s + j * %s + c;" % (base, stride))
    w(ind(lvl + 1) + "%s[e] = %s | (%s << 16);" % (tile, get(arr, "g", "(j < %s) & (c < d)" % limit, half), get(arr, "g + 1", "(j < %s) & (c + 1 < d)" % limit, half)))
    w(ind(lvl) + "}")


def prologue(name, sig, blocks_of):
    w("    public static void %s(%s) {" % (name, sig))
    w(ind(2) + "int tid = kc.localIdx;")
    w(ind(2) + "int lane = tid & 31;")
    w(ind(2) + "int warp = tid >> 5;")
    w(ind(2) + "int quad = lane & 3;")
    w(ind(2) + "int r0 = warp * 16 + (lane >> 2);")
    w(ind(2) + "int r1 = r0 + 8;")
    w(ind(2) + "int blocks = (%s + %d) / %d;" % (blocks_of, BQ - 1, BQ))
    w(ind(2) + "int z = kc.groupIdx / blocks;")
    w(ind(2) + "int x0 = (kc.groupIdx - z * blocks) * %d;" % BQ)
    for line in ["int heads = meta.get(0);", "int b = z / heads;", "int hh = z - b * heads;",
                 "int qBase = meta.get(5) + b * meta.get(6) + hh * meta.get(7);", "int qStr = meta.get(8);",
                 "int kBase = meta.get(9) + b * meta.get(10) + hh * meta.get(11);", "int kStr = meta.get(12);",
                 "int vBase = meta.get(13) + b * meta.get(14) + hh * meta.get(15);", "int vStr = meta.get(16);",
                 "int oBase = meta.get(17) + b * meta.get(18) + hh * meta.get(19);", "int oStr = meta.get(20);",
                 "int mBase = b * meta.get(1) + hh * meta.get(2);", "int mi = meta.get(3);", "int mj = meta.get(4);"]:
        w(ind(2) + line)


def scores(sfrag, gfrag, rowexpr, colexpr, qexpr, kexpr, lseexpr, deltaexpr, pname, dsname, nbs):
    """P and dS from the S and dP accumulators: element e of block nb is row rowexpr(e), column colexpr(nb, e)."""
    for nb in range(nbs):
        for e in range(4):
            w(ind(3) + "float %s%d%d = 0.0f;" % (pname, nb, e))
            w(ind(3) + "float %s%d%d = 0.0f;" % (dsname, nb, e))
            w(ind(3) + "{")
            w(ind(4) + "int qi = %s;" % qexpr(nb, e))
            w(ind(4) + "int j = %s;" % kexpr(nb, e))
            w(ind(4) + "float li = %s;" % lseexpr(nb, e))
            w(ind(4) + "if ((qi < t) & (j < s) & ((causal == 0) | (j <= qi)) & (li > -1.0e38f)) {")
            w(ind(5) + "float sv = %s%d[%d] * scale;" % (sfrag, nb, e))
            w(ind(5) + "if (hasMask != 0) {")
            w(ind(6) + "sv += mask.get(mBase + qi * mi + j * mj);")
            w(ind(5) + "}")
            w(ind(5) + "float p = TornadoMath.exp(sv - li);")
            w(ind(5) + "%s%d%d = p;" % (pname, nb, e))
            w(ind(5) + "%s%d%d = p * (%s%d[%d] - %s);" % (dsname, nb, e, gfrag, nb, e, deltaexpr(nb, e)))
            w(ind(4) + "}")
            w(ind(3) + "}")


def load_a(lvl, *pairs):
    """This warp's A fragments over the head dimension from each (name, tile)."""
    for kb in range(KB):
        for name, tile in pairs:
            w(ind(lvl) + "HalfFloat[] %s%d = kc.mmaLoadA(%s, 16, (warp * %d + %d) * 512);" % (name, kb, tile, KB, kb))


def store_a(tile, vals, nbs):
    """Per-warp A blocks (16 rows x TB) from accumulator-layout values: column nb * 8 + quad * 2."""
    kbs = TB // 16
    for nb in range(nbs):
        kb = nb // 2
        cpo = (nb % 2) * 4
        w(ind(3) + "%s[((warp * %d + %d) * 16 + (lane >> 2)) * 8 + %d + quad] = pack(%s%d0, %s%d1);" % (tile, kbs, kb, cpo, vals, nb, vals, nb))
        w(ind(3) + "%s[((warp * %d + %d) * 16 + (lane >> 2) + 8) * 8 + %d + quad] = pack(%s%d2, %s%d3);" % (tile, kbs, kb, cpo, vals, nb, vals, nb))





def gen_forward():
    w("    public static void forward" + str(D) + "(KernelContext kc, HalfFloatArray q, HalfFloatArray k, HalfFloatArray v, FloatArray mask, HalfFloatArray o, FloatArray lse, int t, int s, int d,")
    w("            float scale, int causal, int hasMask, IntArray meta) {")
    i = 2
    w(ind(i) + "int[] qT = kc.allocateIntLocalArray(%d);" % (BQ * D // 2))
    w(ind(i) + "int[] kT = kc.allocateIntLocalArray(%d);" % (BK * D // 2))
    w(ind(i) + "int[] vT = kc.allocateIntLocalArray(%d);" % (BK * D // 2))
    w(ind(i) + "int[] pT = kc.allocateIntLocalArray(%d);" % (BQ * BK // 2))
    w(ind(i) + "float[] red = kc.allocateFloatLocalArray(%d);" % (BQ * 4))
    w(ind(i) + "int tid = kc.localIdx;")
    w(ind(i) + "int lane = tid & 31;")
    w(ind(i) + "int warp = tid >> 5;")
    w(ind(i) + "int quad = lane & 3;")
    w(ind(i) + "int r0 = warp * 16 + (lane >> 2);")
    w(ind(i) + "int r1 = r0 + 8;")
    w(ind(i) + "int qBlocks = (t + %d) / %d;" % (BQ - 1, BQ))
    w(ind(i) + "int z = kc.groupIdx / qBlocks;")
    w(ind(i) + "int q0 = (kc.groupIdx - z * qBlocks) * %d;" % BQ)
    w(ind(i) + "int heads = meta.get(0);")
    w(ind(i) + "int b = z / heads;")
    w(ind(i) + "int hh = z - b * heads;")
    w(ind(i) + "int qBase = meta.get(5) + b * meta.get(6) + hh * meta.get(7);")
    w(ind(i) + "int qStr = meta.get(8);")
    w(ind(i) + "int kBase = meta.get(9) + b * meta.get(10) + hh * meta.get(11);")
    w(ind(i) + "int kStr = meta.get(12);")
    w(ind(i) + "int vBase = meta.get(13) + b * meta.get(14) + hh * meta.get(15);")
    w(ind(i) + "int vStr = meta.get(16);")
    w(ind(i) + "int oBase = meta.get(17) + b * meta.get(18) + hh * meta.get(19);")
    w(ind(i) + "int oStr = meta.get(20);")
    w(ind(i) + "int mBase = b * meta.get(1) + hh * meta.get(2);")
    w(ind(i) + "int mi = meta.get(3);")
    w(ind(i) + "int mj = meta.get(4);")
    # stage Q: block (rb, kb) of 16x16 at ((rb*KB + kb)*16 + r)*8 + cp
    w(ind(i) + "// Q in A blocks: block (rb, kb), row r, column pair cp at ((rb * %d + kb) * 16 + r) * 8 + cp" % KB)
    w(ind(i) + "for (int e = tid; e < %d; e += %d) {" % (BQ * D // 2, THREADS))
    w(ind(i + 1) + "int cp = e & 7;")
    w(ind(i + 1) + "int r = (e >> 3) & 15;")
    w(ind(i + 1) + "int blk = e >> 7;")
    w(ind(i + 1) + "int rb = blk / %d;" % KB)
    w(ind(i + 1) + "int kb = blk - rb * %d;" % KB)
    w(ind(i + 1) + "int row = q0 + rb * 16 + r;")
    w(ind(i + 1) + "int c = kb * 16 + cp * 2;")
    w(ind(i + 1) + "int g = qBase + row * qStr + c;")
    w(ind(i + 1) + "qT[e] = bits(q, g, (row < t) & (c < d)) | (bits(q, g + 1, (row < t) & (c + 1 < d)) << 16);")
    w(ind(i) + "}")
    w(ind(i) + "kc.localBarrier();")
    for kb in range(KB):
        w(ind(i) + "HalfFloat[] aq%d = kc.mmaLoadA(qT, 16, (warp * %d + %d) * 512);" % (kb, KB, kb))
    w(ind(i) + "float m0 = MASKED;")
    w(ind(i) + "float m1 = MASKED;")
    w(ind(i) + "float l0 = 0.0f;")
    w(ind(i) + "float l1 = 0.0f;")
    for nb in range(NB_O):
        for e in range(4):
            w(ind(i) + "float o%d%d = 0.0f;" % (nb, e))
    w(ind(i) + "int kEnd = s;")
    w(ind(i) + "if (causal != 0) {")
    w(ind(i + 1) + "int last = q0 + %d;" % BQ)
    w(ind(i + 1) + "kEnd = last < s ? last : s;")
    w(ind(i) + "}")
    w(ind(i) + "for (int j0 = 0; j0 < kEnd; j0 += %d) {" % BK)
    i = 3
    # stage K as B for S (k = dim, n = key): block (kb, nb) of 16x8 at ((kb*NB_S + nb)*16 + kr)*4 + np
    w(ind(i) + "// K^T in B blocks (k = head dimension, n = key): ((kb * %d + nb) * 16 + kr) * 4 + np" % NB_S)
    w(ind(i) + "// V in B blocks (k = key, n = head dimension): ((kb * %d + nb) * 16 + kr) * 4 + np" % NB_O)
    w(ind(i) + "for (int e = tid; e < %d; e += %d) {" % (BK * D // 2, THREADS))
    w(ind(i + 1) + "int np = e & 3;")
    w(ind(i + 1) + "int kr = (e >> 2) & 15;")
    w(ind(i + 1) + "int blk = e >> 6;")
    w(ind(i + 1) + "int kb = blk / %d;" % NB_S)
    w(ind(i + 1) + "int nb = blk - kb * %d;" % NB_S)
    w(ind(i + 1) + "int j = j0 + nb * 8 + np * 2;")
    w(ind(i + 1) + "int c = kb * 16 + kr;")
    w(ind(i + 1) + "int g = kBase + j * kStr + c;")
    w(ind(i + 1) + "kT[e] = bits(k, g, (j < s) & (c < d)) | (bits(k, g + kStr, (j + 1 < s) & (c < d)) << 16);")
    w(ind(i + 1) + "int kbv = blk / %d;" % NB_O)
    w(ind(i + 1) + "int nbv = blk - kbv * %d;" % NB_O)
    w(ind(i + 1) + "int jv = j0 + kbv * 16 + kr;")
    w(ind(i + 1) + "int cv = nbv * 8 + np * 2;")
    w(ind(i + 1) + "int gv = vBase + jv * vStr + cv;")
    w(ind(i + 1) + "vT[e] = bits(v, gv, (jv < s) & (cv < d)) | (bits(v, gv + 1, (jv < s) & (cv + 1 < d)) << 16);")
    w(ind(i) + "}")
    w(ind(i) + "kc.localBarrier();")
    # S
    for nb in range(NB_S):
        w(ind(i) + "float[] s%d = kc.mmaFragment(0.0f);" % nb)
    for kb in range(KB):
        for nb in range(NB_S):
            w(ind(i) + "HalfFloat[] bk%d%d = kc.mmaLoadB(kT, 16, %d);" % (kb, nb, (kb * NB_S + nb) * 256))
            w(ind(i) + "s%d = kc.mma(aq%d, bk%d%d, s%d, MMAShape.M16N8K16);" % (nb, kb, kb, nb, nb))
    # scale, mask -> x values
    w(ind(i) + "int qi0 = q0 + r0;")
    w(ind(i) + "int qi1 = q0 + r1;")
    w(ind(i) + "float t0 = MASKED;")
    w(ind(i) + "float t1 = MASKED;")
    for nb in range(NB_S):
        for e in range(4):
            row = "qi0" if e < 2 else "qi1"
            w(ind(i) + "float x%d%d = MASKED;" % (nb, e))
            w(ind(i) + "{")
            w(ind(i + 1) + "int j = j0 + %d + quad * 2;" % (nb * 8 + (e % 2)))
            w(ind(i + 1) + "if ((%s < t) & (j < s) & ((causal == 0) | (j <= %s))) {" % (row, row))
            w(ind(i + 2) + "float sv = s%d[%d] * scale;" % (nb, e))
            w(ind(i + 2) + "if (hasMask != 0) {")
            w(ind(i + 3) + "sv += mask.get(mBase + %s * mi + j * mj);" % row)
            w(ind(i + 2) + "}")
            w(ind(i + 2) + "x%d%d = sv;" % (nb, e))
            w(ind(i + 1) + "}")
            w(ind(i) + "}")
            tv = "t0" if e < 2 else "t1"
            w(ind(i) + "%s = TornadoMath.max(%s, x%d%d);" % (tv, tv, nb, e))
    # row max through shared memory
    w(ind(i) + "red[r0 * 4 + quad] = t0;")
    w(ind(i) + "red[r1 * 4 + quad] = t1;")
    w(ind(i) + "kc.localBarrier();")
    w(ind(i) + "float n0 = TornadoMath.max(m0, TornadoMath.max(TornadoMath.max(red[r0 * 4], red[r0 * 4 + 1]), TornadoMath.max(red[r0 * 4 + 2], red[r0 * 4 + 3])));")
    w(ind(i) + "float n1 = TornadoMath.max(m1, TornadoMath.max(TornadoMath.max(red[r1 * 4], red[r1 * 4 + 1]), TornadoMath.max(red[r1 * 4 + 2], red[r1 * 4 + 3])));")
    w(ind(i) + "float al0 = TornadoMath.exp(m0 - n0);")
    w(ind(i) + "float al1 = TornadoMath.exp(m1 - n1);")
    w(ind(i) + "m0 = n0;")
    w(ind(i) + "m1 = n1;")
    w(ind(i) + "l0 *= al0;")
    w(ind(i) + "l1 *= al1;")
    for nb in range(NB_S):
        for e in range(4):
            mv = "n0" if e < 2 else "n1"
            lv = "l0" if e < 2 else "l1"
            w(ind(i) + "float p%d%d = x%d%d > -1.0e38f ? TornadoMath.exp(x%d%d - %s) : 0.0f;" % (nb, e, nb, e, nb, e, mv))
            w(ind(i) + "%s += p%d%d;" % (lv, nb, e))
    # P into A blocks of this warp: key kk = nb*8 + quad*2 -> kb = nb/2, cp = (nb%2)*4 + quad
    for nb in range(NB_S):
        kb = nb // 2
        cpo = (nb % 2) * 4
        w(ind(i) + "pT[((warp * %d + %d) * 16 + (lane >> 2)) * 8 + %d + quad] = pack(p%d0, p%d1);" % (KB_P, kb, cpo, nb, nb))
        w(ind(i) + "pT[((warp * %d + %d) * 16 + (lane >> 2) + 8) * 8 + %d + quad] = pack(p%d2, p%d3);" % (KB_P, kb, cpo, nb, nb))
    w(ind(i) + "kc.localBarrier();")
    for kb in range(KB_P):
        w(ind(i) + "HalfFloat[] ap%d = kc.mmaLoadA(pT, 16, (warp * %d + %d) * 512);" % (kb, KB_P, kb))
    for nb in range(NB_O):
        w(ind(i) + "float[] f%d = kc.mmaFragment(0.0f);" % nb)
        for kb in range(KB_P):
            w(ind(i) + "HalfFloat[] bv%d%d = kc.mmaLoadB(vT, 16, %d);" % (kb, nb, (kb * NB_O + nb) * 256))
            w(ind(i) + "f%d = kc.mma(ap%d, bv%d%d, f%d, MMAShape.M16N8K16);" % (nb, kb, kb, nb, nb))
        for e in range(4):
            al = "al0" if e < 2 else "al1"
            w(ind(i) + "o%d%d = o%d%d * %s + f%d[%d];" % (nb, e, nb, e, al, nb, e))
    w(ind(i) + "kc.localBarrier();")
    i = 2
    w(ind(i) + "}")
    # final row sums
    w(ind(i) + "red[r0 * 4 + quad] = l0;")
    w(ind(i) + "red[r1 * 4 + quad] = l1;")
    w(ind(i) + "kc.localBarrier();")
    w(ind(i) + "float s0 = red[r0 * 4] + red[r0 * 4 + 1] + red[r0 * 4 + 2] + red[r0 * 4 + 3];")
    w(ind(i) + "float s1 = red[r1 * 4] + red[r1 * 4 + 1] + red[r1 * 4 + 2] + red[r1 * 4 + 3];")
    w(ind(i) + "float inv0 = s0 > 0.0f ? 1.0f / s0 : 0.0f;")
    w(ind(i) + "float inv1 = s1 > 0.0f ? 1.0f / s1 : 0.0f;")
    w(ind(i) + "int qi0 = q0 + r0;")
    w(ind(i) + "int qi1 = q0 + r1;")
    for nb in range(NB_O):
        for e in range(4):
            row = "qi0" if e < 2 else "qi1"
            inv = "inv0" if e < 2 else "inv1"
            w(ind(i) + "{")
            w(ind(i + 1) + "int c = %d + quad * 2;" % (nb * 8 + (e % 2)))
            w(ind(i + 1) + "if ((%s < t) & (c < d)) {" % row)
            w(ind(i + 2) + "o.set(oBase + %s * oStr + c, new HalfFloat(o%d%d * %s));" % (row, nb, e, inv))
            w(ind(i + 1) + "}")
            w(ind(i) + "}")
    w(ind(i) + "if ((quad == 0) & (qi0 < t)) {")
    w(ind(i + 1) + "lse.set(z * t + qi0, s0 > 0.0f ? m0 + TornadoMath.log(s0) : MASKED);")
    w(ind(i) + "}")
    w(ind(i) + "if ((quad == 0) & (qi1 < t)) {")
    w(ind(i + 1) + "lse.set(z * t + qi1, s1 > 0.0f ? m1 + TornadoMath.log(s1) : MASKED);")
    w(ind(i) + "}")
    w("    }")
    w("")



def gen_backward_q(reload):
    # backwardQ: 64 queries per work-group, keys streamed in tiles of TB
    prologue("backwardQ" + str(D), "KernelContext kc, HalfFloatArray q, HalfFloatArray k, HalfFloatArray v, FloatArray mask, HalfFloatArray o, FloatArray dout, FloatArray lse, "
             "FloatArray delta,\n            FloatArray dq, int t, int s, int d, float scale, int causal, int hasMask, IntArray meta", "t")
    w(ind(2) + "int[] qA = kc.allocateIntLocalArray(%d);" % (BQ * D // 2))
    w(ind(2) + "int[] dA = kc.allocateIntLocalArray(%d);" % (BQ * D // 2))
    w(ind(2) + "int[] kT = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] vT = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] kB = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] sA = kc.allocateIntLocalArray(%d);" % (BQ * TB // 2))
    w(ind(2) + "float[] red = kc.allocateFloatLocalArray(%d);" % (2 * BQ))
    w(ind(2) + "float[] ls = kc.allocateFloatLocalArray(%d);" % BQ)
    w(ind(2) + "float[] dl = kc.allocateFloatLocalArray(%d);" % BQ)
    stage_a("qA", "q", "qBase", "qStr", "x0", "t", True, BQ)
    stage_a("dA", "dout", "oBase", "oStr", "x0", "t", False, BQ)
    w(ind(2) + "// delta = rowsum(dO * O), two threads per query; written for backwardKV, which runs next")
    w(ind(2) + "{")
    w(ind(3) + "int row = tid >> 1;")
    w(ind(3) + "int half = tid & 1;")
    w(ind(3) + "int qi = x0 + row;")
    w(ind(3) + "float acc = 0.0f;")
    w(ind(3) + "if (qi < t) {")
    w(ind(4) + "for (int c = half * %d; c < half * %d + %d; c++) {" % (D // 2, D // 2, D // 2))
    w(ind(5) + "if (c < d) {")
    w(ind(6) + "acc += dout.get(oBase + qi * oStr + c) * o.get(oBase + qi * oStr + c).getFloat32();")
    w(ind(5) + "}")
    w(ind(4) + "}")
    w(ind(3) + "}")
    w(ind(3) + "red[tid] = acc;")
    w(ind(2) + "}")
    w(ind(2) + "kc.localBarrier();")
    w(ind(2) + "if (tid < %d) {" % BQ)
    w(ind(3) + "float di = red[2 * tid] + red[2 * tid + 1];")
    w(ind(3) + "float li = MASKED;")
    w(ind(3) + "if (x0 + tid < t) {")
    w(ind(4) + "li = lse.get(z * t + x0 + tid);")
    w(ind(4) + "delta.set(z * t + x0 + tid, di);")
    w(ind(3) + "}")
    w(ind(3) + "ls[tid] = li;")
    w(ind(3) + "dl[tid] = di;")
    w(ind(2) + "}")
    w(ind(2) + "kc.localBarrier();")
    if not reload:
        load_a(2, ("aq", "qA"), ("ad", "dA"))
    w(ind(2) + "float l0 = ls[r0];")
    w(ind(2) + "float l1 = ls[r1];")
    w(ind(2) + "float e0 = dl[r0];")
    w(ind(2) + "float e1 = dl[r1];")
    for nb in range(NB_O):
        w(ind(2) + "float[] dq%d = kc.mmaFragment(0.0f);" % nb)
    w(ind(2) + "int kEnd = s;")
    w(ind(2) + "if (causal != 0) {")
    w(ind(3) + "int last = x0 + %d;" % BQ)
    w(ind(3) + "kEnd = last < s ? last : s;")
    w(ind(2) + "}")
    w(ind(2) + "for (int j0 = 0; j0 < kEnd; j0 += %d) {" % TB)
    stage_bt("kT", "k", "kBase", "kStr", "j0", "s", True, 3)
    stage_bt("vT", "v", "vBase", "vStr", "j0", "s", True, 3)
    stage_b("kB", "k", "kBase", "kStr", "j0", "s", True, 3)
    w(ind(3) + "kc.localBarrier();")
    if reload:
        load_a(3, ("aq", "qA"), ("ad", "dA"))
    for nb in range(NBT):
        w(ind(3) + "float[] s%d = kc.mmaFragment(0.0f);" % nb)
        w(ind(3) + "float[] g%d = kc.mmaFragment(0.0f);" % nb)
    for kb in range(KB):
        for nb in range(NBT):
            w(ind(3) + "s%d = kc.mma(aq%d, kc.mmaLoadB(kT, 16, %d), s%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NBT + nb) * 256, nb))
            w(ind(3) + "g%d = kc.mma(ad%d, kc.mmaLoadB(vT, 16, %d), g%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NBT + nb) * 256, nb))
    scores("s", "g", None, None,
           lambda nb, e: "x0 + " + ("r0" if e < 2 else "r1"),
           lambda nb, e: "j0 + %d + quad * 2" % (nb * 8 + e % 2),
           lambda nb, e: "l0" if e < 2 else "l1",
           lambda nb, e: "e0" if e < 2 else "e1", "p", "w", NBT)
    store_a("sA", "w", NBT)
    w(ind(3) + "kc.localBarrier();")
    for kb in range(KBT):
        w(ind(3) + "HalfFloat[] as%d = kc.mmaLoadA(sA, 16, (warp * %d + %d) * 512);" % (kb, KBT, kb))
    for nb in range(NB_O):
        for kb in range(KBT):
            w(ind(3) + "dq%d = kc.mma(as%d, kc.mmaLoadB(kB, 16, %d), dq%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NB_O + nb) * 256, nb))
    w(ind(3) + "kc.localBarrier();")
    w(ind(2) + "}")
    for nb in range(NB_O):
        for e in range(4):
            w(ind(2) + "{")
            w(ind(3) + "int qi = x0 + %s;" % ("r0" if e < 2 else "r1"))
            w(ind(3) + "int c = %d + quad * 2;" % (nb * 8 + e % 2))
            w(ind(3) + "if ((qi < t) & (c < d)) {")
            w(ind(4) + "dq.set(qBase + qi * qStr + c, dq%d[%d] * scale);" % (nb, e))
            w(ind(3) + "}")
            w(ind(2) + "}")
    w("    }")
    w("")



def gen_backward_kv(reload):
    # backwardKV: 64 keys per work-group, queries streamed in tiles of TB
    prologue("backwardKV" + str(D), "KernelContext kc, HalfFloatArray q, HalfFloatArray k, HalfFloatArray v, FloatArray mask, FloatArray dout, FloatArray lse, FloatArray delta,"
             "\n            FloatArray dk, FloatArray dv, int t, int s, int d, float scale, int causal, int hasMask, IntArray meta", "s")
    w(ind(2) + "int[] kA = kc.allocateIntLocalArray(%d);" % (BQ * D // 2))
    w(ind(2) + "int[] vA = kc.allocateIntLocalArray(%d);" % (BQ * D // 2))
    w(ind(2) + "int[] qT = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] dT = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] qB = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] dB = kc.allocateIntLocalArray(%d);" % (TB * D // 2))
    w(ind(2) + "int[] pA = kc.allocateIntLocalArray(%d);" % (BQ * TB // 2))
    w(ind(2) + "int[] sA = kc.allocateIntLocalArray(%d);" % (BQ * TB // 2))
    w(ind(2) + "float[] ls = kc.allocateFloatLocalArray(%d);" % TB)
    w(ind(2) + "float[] dl = kc.allocateFloatLocalArray(%d);" % TB)
    stage_a("kA", "k", "kBase", "kStr", "x0", "s", True, BQ)
    stage_a("vA", "v", "vBase", "vStr", "x0", "s", True, BQ)
    w(ind(2) + "kc.localBarrier();")
    if not reload:
        load_a(2, ("ak", "kA"), ("av", "vA"))
    for nb in range(NB_O):
        w(ind(2) + "float[] dk%d = kc.mmaFragment(0.0f);" % nb)
        w(ind(2) + "float[] dv%d = kc.mmaFragment(0.0f);" % nb)
    w(ind(2) + "int iStart = 0;")
    w(ind(2) + "if (causal != 0) {")
    w(ind(3) + "iStart = x0;")
    w(ind(2) + "}")
    w(ind(2) + "for (int i0 = iStart; i0 < t; i0 += %d) {" % TB)
    stage_bt("qT", "q", "qBase", "qStr", "i0", "t", True, 3)
    stage_bt("dT", "dout", "oBase", "oStr", "i0", "t", False, 3)
    stage_b("qB", "q", "qBase", "qStr", "i0", "t", True, 3)
    stage_b("dB", "dout", "oBase", "oStr", "i0", "t", False, 3)
    w(ind(3) + "if (tid < %d) {" % TB)
    w(ind(4) + "float li = MASKED;")
    w(ind(4) + "float di = 0.0f;")
    w(ind(4) + "if (i0 + tid < t) {")
    w(ind(5) + "li = lse.get(z * t + i0 + tid);")
    w(ind(5) + "di = delta.get(z * t + i0 + tid);")
    w(ind(4) + "}")
    w(ind(4) + "ls[tid] = li;")
    w(ind(4) + "dl[tid] = di;")
    w(ind(3) + "}")
    w(ind(3) + "kc.localBarrier();")
    if reload:
        load_a(3, ("ak", "kA"), ("av", "vA"))
    for nb in range(NBT):
        w(ind(3) + "float[] s%d = kc.mmaFragment(0.0f);" % nb)
        w(ind(3) + "float[] g%d = kc.mmaFragment(0.0f);" % nb)
    for kb in range(KB):
        for nb in range(NBT):
            w(ind(3) + "s%d = kc.mma(ak%d, kc.mmaLoadB(qT, 16, %d), s%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NBT + nb) * 256, nb))
            w(ind(3) + "g%d = kc.mma(av%d, kc.mmaLoadB(dT, 16, %d), g%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NBT + nb) * 256, nb))
    scores("s", "g", None, None,
           lambda nb, e: "i0 + %d + quad * 2" % (nb * 8 + e % 2),
           lambda nb, e: "x0 + " + ("r0" if e < 2 else "r1"),
           lambda nb, e: "ls[%d + quad * 2]" % (nb * 8 + e % 2),
           lambda nb, e: "dl[%d + quad * 2]" % (nb * 8 + e % 2), "p", "w", NBT)
    store_a("pA", "p", NBT)
    store_a("sA", "w", NBT)
    w(ind(3) + "kc.localBarrier();")
    for kb in range(KBT):
        w(ind(3) + "HalfFloat[] ap%d = kc.mmaLoadA(pA, 16, (warp * %d + %d) * 512);" % (kb, KBT, kb))
        w(ind(3) + "HalfFloat[] as%d = kc.mmaLoadA(sA, 16, (warp * %d + %d) * 512);" % (kb, KBT, kb))
    for nb in range(NB_O):
        for kb in range(KBT):
            w(ind(3) + "dv%d = kc.mma(ap%d, kc.mmaLoadB(dB, 16, %d), dv%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NB_O + nb) * 256, nb))
            w(ind(3) + "dk%d = kc.mma(as%d, kc.mmaLoadB(qB, 16, %d), dk%d, MMAShape.M16N8K16);" % (nb, kb, (kb * NB_O + nb) * 256, nb))
    w(ind(3) + "kc.localBarrier();")
    w(ind(2) + "}")
    for nb in range(NB_O):
        for e in range(4):
            w(ind(2) + "{")
            w(ind(3) + "int j = x0 + %s;" % ("r0" if e < 2 else "r1"))
            w(ind(3) + "int c = %d + quad * 2;" % (nb * 8 + e % 2))
            w(ind(3) + "if ((j < s) & (c < d)) {")
            w(ind(4) + "dk.set(kBase + j * kStr + c, dk%d[%d] * scale);" % (nb, e))
            w(ind(4) + "dv.set(vBase + j * vStr + c, dv%d[%d]);" % (nb, e))
            w(ind(3) + "}")
            w(ind(2) + "}")
    w("    }")


