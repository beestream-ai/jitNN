"""Channels-last Winograd F(4x4, 3x3) transforms, derived from the NCHW ones in ConvKernels.java.

usage: python3 scripts/codegen/winograd_channels_last.py > jitnn-core/src/main/java/org/beehive/jitnn/kernels/ConvChannelsLastKernels.java

The input transform reads x [N, H, W, C] (FP32 or FP16) into v [36, tiles, C]; the weight transform
writes u [36, Cin, Cout]; the 36 products mm = v u are [36, tiles, Cout]; the output transform writes
out [N, OH, OW, C] (FP32 or FP16) with the bias and ReLU epilogue. Work-items run channel-fastest
(idx = tile * C + channel), so every read and write coalesces.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "jitnn-core", "src", "main", "java", "org", "beehive", "jitnn", "kernels", "ConvKernels.java")


def method(text, name):
    start = text.index("    public static void " + name + "(")
    end = text.index("\n    }\n", start) + len("\n    }\n")
    return text[start:end]


def input_last(body, half):
    name = "winograd4InputLastHalf" if half else "winograd4InputLast"
    body = body.replace("public static void winograd4Input(KernelContext kc, FloatArray x,",
                        f"public static void {name}(KernelContext kc, {'HalfFloatArray' if half else 'FloatArray'} x,")
    body = body.replace("int ci = idx / tiles;", "int ci = idx % c;")
    body = body.replace("int p = idx - ci * tiles;", "int p = idx / c;")
    body = re.sub(r"\n *int base = \(n \* c \+ ci\) \* h \* wd;", "", body)
    read = r"x.get(((n * h + r0 + \1) * wd + c0 + \2) * c + ci)" + (".getFloat32()" if half else "")
    body = re.sub(r"x\.get\(base \+ \(r0 \+ (\d)\) \* wd \+ c0 \+ (\d)\)", read, body)
    assert "base" not in body, name
    return body


def output_last(body, half):
    name = "winograd4OutputLastHalf" if half else "winograd4OutputLast"
    body = body.replace("public static void winograd4Output(KernelContext kc, FloatArray mm, FloatArray out,",
                        f"public static void {name}(KernelContext kc, FloatArray mm, {'HalfFloatArray' if half else 'FloatArray'} out,")
    body = body.replace("int co = idx / tiles;", "int co = idx % c;")
    body = body.replace("int p = idx - co * tiles;", "int p = idx / c;")
    body = re.sub(r"\n *int base = \(n \* c \+ co\) \* oh \* ow;", "", body)
    value = r"new HalfFloat(\3)" if half else r"\3"
    body = re.sub(r"out\.set\(base \+ \(4 \* ty \+ (\d)\) \* ow \+ 4 \* tx \+ (\d), (z\d_\d)\)",
                  r"out.set(((n * oh + 4 * ty + \1) * ow + 4 * tx + \2) * c + co, " + value + ")", body)
    assert "base" not in body, name
    return body


def weight_last(body):
    body = body.replace("public static void winograd4Weight(", "public static void winograd4WeightLast(")
    body = re.sub(r"u\.set\((\d+) \* stride \+ idx,", r"u.set(\1 * stride + q * rows + r,", body)
    assert "+ idx," not in body
    return body


def main():
    text = open(SRC).read()
    inp = method(text, "winograd4Input")
    outp = method(text, "winograd4Output")
    wgt = method(text, "winograd4Weight")
    print("package org.beehive.jitnn.kernels;")
    print()
    print("import uk.ac.manchester.tornado.api.KernelContext;")
    print("import uk.ac.manchester.tornado.api.types.HalfFloat;")
    print("import uk.ac.manchester.tornado.api.types.arrays.FloatArray;")
    print("import uk.ac.manchester.tornado.api.types.arrays.HalfFloatArray;")
    print()
    print("/**")
    print(" * Winograd F(4x4, 3x3) transforms on channels-last tensors: x [N, H, W, C] into v [36, tiles, C], the")
    print(" * weight into u [36, Cin, Cout], and the products mm [36, tiles, Cout] into out [N, OH, OW, C] with the")
    print(" * bias and ReLU epilogue. Generated by scripts/codegen/winograd_channels_last.py from ConvKernels'")
    print(" * NCHW transforms; do not edit by hand.")
    print(" */")
    print("public final class ConvChannelsLastKernels {")
    print()
    print("    private ConvChannelsLastKernels() {")
    print("    }")
    for body in (input_last(inp, False), input_last(inp, True), weight_last(wgt), output_last(outp, False), output_last(outp, True)):
        print()
        sys.stdout.write(body)
    print("}")


if __name__ == "__main__":
    main()
