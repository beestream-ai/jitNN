"""Generates FlashTiled64Half from FlashTiled64 (scripts/codegen/flash_tiled.py): the same tiled
FlashAttention-2 forward, reading q, k, v and writing o in FP16 (HalfFloatArray) while every
product, the online softmax and the accumulators stay FP32; and the backward kernels reading q, k,
v and o in FP16 (FP16 training), with FP32 gradients dO in and dQ, dK, dV out. Prints the Java class.

    python scripts/codegen/flash_tiled_half.py > jitnn-core/src/main/java/ai/beestream/jitnn/kernels/FlashTiled64Half.java
"""
import re
import sys
from pathlib import Path

src = Path(__file__).resolve().parents[2] / "jitnn-core/src/main/java/ai/beestream/jitnn/kernels/FlashTiled64.java"
text = src.read_text()
start = text.index("    public static void forward(")
end = text.index("    public static void backwardKV(")
body = text[start:end].rstrip()
# the javadoc of backwardKV may precede it; cut forward at its closing brace
body = body[: body.rindex("\n    }") + len("\n    }")]
body = body.replace("FloatArray q, FloatArray k, FloatArray v, FloatArray mask, FloatArray o,",
                    "HalfFloatArray q, HalfFloatArray k, HalfFloatArray v, FloatArray mask, HalfFloatArray o,")
body = re.sub(r"\b([qkv])\.get\(([^;]*?)\);", r"\1.get(\2).getFloat32();", body)
body = re.sub(r"\bo\.set\(([^,]+), ([^;]*)\);", r"o.set(\1, new HalfFloat(\2));", body)
assert "HalfFloatArray q" in body and ".getFloat32()" in body and "new HalfFloat(" in body


def backward(name, nxt):
    b0 = text.index(f"    public static void {name}(")
    b1 = text.index(nxt, b0) if nxt else len(text)
    part = text[b0:b1].rstrip()
    part = part[: part.rindex("\n    }") + len("\n    }")]
    part = part.replace("FloatArray q, FloatArray k, FloatArray v, FloatArray mask,", "HalfFloatArray q, HalfFloatArray k, HalfFloatArray v, FloatArray mask,")
    part = part.replace("FloatArray mask, FloatArray o,", "FloatArray mask, HalfFloatArray o,")
    # q, k, v and o are read as FP16; every other array (dout, lse, delta, the gradients) stays FP32
    part = re.sub(r"\b([qkvo])\.get\(([^;]*?)\);", r"\1.get(\2).getFloat32();", part)
    assert "HalfFloatArray q" in part and ".getFloat32()" in part
    return part


body = body + "\n\n" + backward("backwardKV", "    public static void backwardQ(") + "\n\n" + backward("backwardQ", None)
out = sys.stdout
out.write("""package ai.beestream.jitnn.kernels;

import uk.ac.manchester.tornado.api.KernelContext;
import uk.ac.manchester.tornado.api.math.TornadoMath;
import uk.ac.manchester.tornado.api.types.HalfFloat;
import uk.ac.manchester.tornado.api.types.arrays.FloatArray;
import uk.ac.manchester.tornado.api.types.arrays.HalfFloatArray;
import uk.ac.manchester.tornado.api.types.arrays.IntArray;

/**
 * {@link FlashTiled64#forward} on FP16 q, k, v and o (FP32 products, softmax and accumulators),
 * generated by scripts/codegen/flash_tiled_half.py: half the memory traffic of the FP32 kernel for
 * inference in half precision. Same launch, meta layout, mask and lse. The backward kernels read
 * FP16 q, k, v and o and take and write FP32 gradients (training with FP16 activations), with the
 * launches of {@link FlashTiled64#backwardKV} and {@link FlashTiled64#backwardQ}.
 */
public final class FlashTiled64Half {

    private static final float MASKED = -3.0e38f;

    private FlashTiled64Half() {
    }

""")
out.write(body + "\n}\n")
