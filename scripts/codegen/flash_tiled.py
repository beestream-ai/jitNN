w("            ls[tid] = li;")
w("            dl[tid] = di;")
w("        }")
w("        kc.localBarrier();")
for a in range(2):
    for c in range(4):
        w(f"        float dq{a}{c} = 0.0f;")
w("        int kEnd = s;")
w("        if (causal != 0) {")
w(f"            int last = r0 + {TB};")
w("            kEnd = last < s ? last : s;")
w("        }")
w(f"        for (int j0 = 0; j0 < kEnd; j0 += {TB}) {{")
load2("xs", "k", "kBase", "kStr", "ys", "v", "vBase", "vStr", "j0", "s", "            ")
w("            kc.localBarrier();")
scores("as", "xs", "bs", "ys", False, "            ")
w("            kc.localBarrier();")
w(f"            for (int jj = 0; jj < {TB}; jj++) {{")
for a in range(2):
    w(f"                float g{a} = gs[(ty + {16 * a}) * {PP} + jj];")
for c in range(4):
    w(f"                float k{c} = xs[jj * {TP} + tx + {16 * c}];")
for a in range(2):
    for c in range(4):
        w(f"                dq{a}{c} += g{a} * k{c};")
w("            }")
w("            kc.localBarrier();")
w("        }")
for a in range(2):
    w(f"        if (r0 + ty + {16 * a} < t) {{")
    w(f"            int i = r0 + ty + {16 * a};")
