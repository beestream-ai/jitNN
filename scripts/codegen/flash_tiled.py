"""Generates FlashTiled64, jitNN's tiled FlashAttention-2 forward for head dimensions up to 64
(TornadoVM needs the register tiles as scalars). Prints the Java class.

A work-group of 16x16 threads owns BQ = 64 query rows, staged once in local memory; keys and
values stream through in tiles of BK = 32. Per tile: S = Q K^T in 4x2 register blocks (rows
ty + 16 i, keys tx + 16 j), the online softmax with 4 threads per row, then O += P V in 4x4
register blocks (rows ty + 16 i, columns tx + 16 j). Operands are addressed through the same meta
strides as FlashKernels64.
"""
BQ, BK, D = 64, 32, 64
QP, KP, SP = D + 1, D + 1, BK + 1

o = []
w = o.append
w("package org.beehive.jitnn.kernels;")
w("")
w("import uk.ac.manchester.tornado.api.KernelContext;")
w("import uk.ac.manchester.tornado.api.math.TornadoMath;")
w("import uk.ac.manchester.tornado.api.types.arrays.FloatArray;")
w("import uk.ac.manchester.tornado.api.types.arrays.IntArray;")
w("")
w("/**")
w(" * Tiled FlashAttention-2 forward for head dimensions up to 64, generated by scripts/codegen/flash_tiled.py:")
w(f" * a work-group of 16x16 threads owns {BQ} query rows (staged once in local memory) and streams keys and")
w(f" * values through in tiles of {BK}. Per tile it computes S = Q K^T in 4x2 register blocks, updates the online")
w(" * softmax with 4 threads per row, and accumulates O += P V in 4x4 register blocks, so every K and V element")
w(f" * loaded serves {BQ} queries. Same operands, meta layout, masking and outputs (o and the row logsumexp lse)")
w(" * as {@link FlashKernels64#forward}.")
w(" */")
w("public final class FlashTiled64 {")
w("")
w(f"    public static final int D = {D};")
w(f"    /** Query rows per work-group. */")
w(f"    public static final int BQ = {BQ};")
w(f"    /** Keys per tile. */")
w(f"    public static final int BK = {BK};")
w("    public static final int THREADS = 256;")
w("    private static final float MASKED = -3.0e38f;")
w("")
w("    private FlashTiled64() {")
w("    }")
w("")
w(f"    /** Forward: o and lse. Z * ceil(T / {BQ}) work-groups of 16x16 threads. */")
w("    public static void forward(KernelContext kc, FloatArray q, FloatArray k, FloatArray v, FloatArray mask, FloatArray o, FloatArray lse, int t, int s, int d,")
w("            float scale, int causal, int hasMask, IntArray meta) {")
w(f"        float[] qs = kc.allocateFloatLocalArray({BQ * QP});")
w(f"        float[] ks = kc.allocateFloatLocalArray({BK * KP});")
w(f"        float[] vs = kc.allocateFloatLocalArray({BK * KP});")
w(f"        float[] ss = kc.allocateFloatLocalArray({BQ * SP});")
w("        float[] part = kc.allocateFloatLocalArray(256);")
w(f"        float[] mrow = kc.allocateFloatLocalArray({BQ});")
w(f"        float[] lrow = kc.allocateFloatLocalArray({BQ});")
w(f"        float[] arow = kc.allocateFloatLocalArray({BQ});")
w("        int tx = kc.localIdx;")
w("        int ty = kc.localIdy;")
w("        int tid = ty * 16 + tx;")
w(f"        int qBlocks = (t + {BQ - 1}) / {BQ};")
w("        int z = kc.groupIdx / qBlocks;")
w(f"        int q0 = (kc.groupIdx - z * qBlocks) * {BQ};")
w("        int heads = meta.get(0);")
w("        int b = z / heads;")
w("        int hh = z - b * heads;")
w("        int qBase = meta.get(5) + b * meta.get(6) + hh * meta.get(7);")
w("        int qStr = meta.get(8);")
w("        int kBase = meta.get(9) + b * meta.get(10) + hh * meta.get(11);")
w("        int kStr = meta.get(12);")
w("        int vBase = meta.get(13) + b * meta.get(14) + hh * meta.get(15);")
w("        int vStr = meta.get(16);")
w("        int oBase = meta.get(17) + b * meta.get(18) + hh * meta.get(19);")
w("        int oStr = meta.get(20);")
w("        int mBase = b * meta.get(1) + hh * meta.get(2);")
w("        int mi = meta.get(3);")
w("        int mj = meta.get(4);")
w(f"        for (int e = tid; e < {BQ * D}; e += 256) {{")
w(f"            int r = e / {D};")
w(f"            int c = e - r * {D};")
w("            float x = 0.0f;")
w("            if ((q0 + r < t) & (c < d)) {")
w("                x = q.get(qBase + (q0 + r) * qStr + c);")
w("            }")
w(f"            qs[r * {QP} + c] = x;")
w("        }")
w(f"        if (tid < {BQ}) {{")
w("            mrow[tid] = MASKED;")
w("            lrow[tid] = 0.0f;")
w("        }")
for i in range(4):
    for j in range(4):
        w(f"        float acc{i}{j} = 0.0f;")
w("        int kEnd = s;")
w("        if (causal != 0) {")
w(f"            int last = q0 + {BQ};")
w("            kEnd = last < s ? last : s;")
w("        }")
w("        int row = tid / 4;")
w("        int quarter = tid - row * 4;")
w(f"        for (int j0 = 0; j0 < kEnd; j0 += {BK}) {{")
w(f"            for (int e = tid; e < {BK * D}; e += 256) {{")
w(f"                int r = e / {D};")
w(f"                int c = e - r * {D};")
w("                int j = j0 + r;")
w("                float kv = 0.0f;")
w("                float vv = 0.0f;")
w("                if ((j < s) & (c < d)) {")
w("                    kv = k.get(kBase + j * kStr + c);")
w("                    vv = v.get(vBase + j * vStr + c);")
w("                }")
w(f"                ks[r * {KP} + c] = kv;")
w(f"                vs[r * {KP} + c] = vv;")
w("            }")
w("            kc.localBarrier();")
for i in range(4):
    for j in range(2):
        w(f"            float s{i}{j} = 0.0f;")
w(f"            for (int c = 0; c < {D}; c++) {{")
for i in range(4):
    w(f"                float a{i} = qs[(ty + {16 * i}) * {QP} + c];")
for j in range(2):
    w(f"                float k{j} = ks[(tx + {16 * j}) * {KP} + c];")
for i in range(4):
    for j in range(2):
        w(f"                s{i}{j} += a{i} * k{j};")
w("            }")
for i in range(4):
    for j in range(2):
        w("            {")
        w(f"                int qi = q0 + ty + {16 * i};")
        w(f"                int j = j0 + tx + {16 * j};")
        w("                float sv = MASKED;")
        w("                if ((qi < t) & (j < s) & ((causal == 0) | (j <= qi))) {")
        w(f"                    sv = s{i}{j} * scale;")
        w("                    if (hasMask != 0) {")
        w("                        sv += mask.get(mBase + qi * mi + j * mj);")
        w("                    }")
        w("                }")
        w(f"                ss[(ty + {16 * i}) * {SP} + tx + {16 * j}] = sv;")
        w("            }")
w("            kc.localBarrier();")
# softmax: 4 threads per row, 8 keys each
w("            float lm = MASKED;")
w("            for (int c = 0; c < 8; c++) {")
w(f"                float sv = ss[row * {SP} + quarter * 8 + c];")
w("                lm = sv > lm ? sv : lm;")
w("            }")
w("            part[tid] = lm;")
w("            kc.localBarrier();")
w("            float mOld = mrow[row];")
w("            float mNew = mOld;")
w("            for (int c = 0; c < 4; c++) {")
w("                float pm = part[row * 4 + c];")
w("                mNew = pm > mNew ? pm : mNew;")
w("            }")
w("            float ls = 0.0f;")
w("            for (int c = 0; c < 8; c++) {")
w(f"                int at = row * {SP} + quarter * 8 + c;")
w("                float sv = ss[at];")
w("                float p = sv > MASKED ? TornadoMath.exp(sv - mNew) : 0.0f;")
w("                ss[at] = p;")
w("                ls += p;")
w("            }")
w("            kc.localBarrier();")
w("            part[tid] = ls;")
w("            kc.localBarrier();")
w("            if (quarter == 0) {")
w("                float alpha = mOld > MASKED ? TornadoMath.exp(mOld - mNew) : 0.0f;")
w("                lrow[row] = lrow[row] * alpha + part[row * 4] + part[row * 4 + 1] + part[row * 4 + 2] + part[row * 4 + 3];")
w("                mrow[row] = mNew;")
w("                arow[row] = alpha;")
w("            }")
w("            kc.localBarrier();")
for i in range(4):
    w(f"            float al{i} = arow[ty + {16 * i}];")
    for j in range(4):
        w(f"            acc{i}{j} = acc{i}{j} * al{i};")
w(f"            for (int kk = 0; kk < {BK}; kk++) {{")
for i in range(4):
    w(f"                float p{i} = ss[(ty + {16 * i}) * {SP} + kk];")
for j in range(4):
    w(f"                float v{j} = vs[kk * {KP} + tx + {16 * j}];")
for i in range(4):
    for j in range(4):
        w(f"                acc{i}{j} += p{i} * v{j};")
w("            }")
w("            kc.localBarrier();")
w("        }")
for i in range(4):
    w("        {")
    w(f"            int r = ty + {16 * i};")
    w("            int qi = q0 + r;")
    w("            float l = lrow[r];")
    w("            float inv = l > 0.0f ? 1.0f / l : 0.0f;")
    for j in range(4):
        w(f"            if ((qi < t) & (tx + {16 * j} < d)) {{")
        w(f"                o.set(oBase + qi * oStr + tx + {16 * j}, acc{i}{j} * inv);")
        w("            }")
    w("        }")
w(f"        if ((tid < {BQ}) & (q0 + tid < t)) {{")
w("            float l = lrow[tid];")
w("            lse.set(z * t + q0 + tid, l > 0.0f ? mrow[tid] + TornadoMath.log(l) : MASKED);")
w("        }")
w("    }")
w("}")
print("\n".join(o))
