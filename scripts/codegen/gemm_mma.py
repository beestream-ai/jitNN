"""Generates jitNN's tensor-core GEMM for half-precision operands on CUDA (KernelContext MMA,
m16n8k16, FP32 accumulation; compute capability 8.0+).

usage: python gemm_mma.py <name> <f16|bf16>

A work-group is one warp (32 threads) computing a 32x32 block of C[z] = op(A[z]) op(B[z]) as 2 x 4
m16n8 accumulator fragments (one warp per group keeps the fragment code free of per-warp
branches). Each k-step of 16 stages A and B as packed half pairs, one local array per fragment
(the MMA loads take a whole tile), with bounds-checked loads, so M, N and K need not be
multiples of 16. Results are stored
element by element from the fragment registers (lane L holds rows L/4 and L/4 + 8, columns
2 (L % 4) and 2 (L % 4) + 1 of its 16x8 tile), which allows bounds checks, the bias/ReLU
epilogue and batch offsets. Batches are folded into the grid's y dimension as in gemm64Batched.
"""
import sys

NAME, IN = sys.argv[1], sys.argv[2]
ARR = {"f16": "HalfFloatArray", "bf16": "ShortArray"}[IN]
MMA = {"f16": "mma", "bf16": "mmaBF16"}[IN]


def bits(arr, index):
    if IN == "f16":
        return f"({arr}.get({index}).getHalfFloatValue() & 0xFFFF)"
    return f"({arr}.get({index}) & 0xFFFF)"


o = []
w = o.append
w(f"""    /**
     * Tensor-core GEMM on {IN} operands (CUDA, generated by scripts/codegen/gemm_mma.py {NAME} {IN}):
     * C[z] = op(A[z]) op(B[z]) with FP32 accumulation, A[z] at z * strideA, B[z] at z * strideB
     * (0 broadcasts), C[z] at z * m * n. One warp per 32x32 block; launch 32-thread groups over
     * ceil(N/32) x (batch * tilesY) groups, tilesY = ceil(M/32). {{@code epilogue}}: see {{@link #store}}.
     */
    public static void {NAME}(KernelContext kc, {ARR} a, {ARR} b, FloatArray c, FloatArray bias, int m, int n, int k, int transA, int transB, int epilogue, int strideA, int strideB, int tilesY) {{""")
for f in range(2):
    w(f"        int[] at{f} = kc.allocateIntLocalArray(128);")
for g in range(4):
    w(f"        int[] bt{g} = kc.allocateIntLocalArray(64);")
w("""        int lane = kc.localIdx;
        int bz = kc.groupIdy / tilesY;
        int row0 = (kc.groupIdy - bz * tilesY) * 32;
        int col0 = kc.groupIdx * 32;
        int offA = bz * strideA;
        int offB = bz * strideB;
        int offC = bz * m * n;""")
for i in range(2):
    for j in range(4):
        w(f"        float[] acc{i}{j} = kc.mmaFragment(0.0f);")
w("        for (int k0 = 0; k0 < k; k0 += 16) {")
# A fragment f: rows row0 + 16 f + r, int e = r * 8 + pair (128 ints, 4 per lane)
for f in range(2):
    w(f"            for (int e = lane; e < 128; e += 32) {{")
    w(f"                int gr = row0 + {16 * f} + e / 8;")
    w(f"                int ak = k0 + 2 * (e - (e / 8) * 8);")
    w(f"                int lo = 0;")
    w(f"                int hi = 0;")
    w(f"                if (gr < m) {{")
    w(f"                    if (ak < k) {{")
    w(f"                        lo = transA == 0 ? {bits('a', 'offA + gr * k + ak')} : {bits('a', 'offA + ak * m + gr')};")
    w(f"                    }}")
    w(f"                    if (ak + 1 < k) {{")
    w(f"                        hi = transA == 0 ? {bits('a', 'offA + gr * k + ak + 1')} : {bits('a', 'offA + (ak + 1) * m + gr')};")
    w(f"                    }}")
    w(f"                }}")
    w(f"                at{f}[e] = lo | (hi << 16);")
    w(f"            }}")
# B fragment g: columns col0 + 8 g + 2 pair (+1), int e = kRow * 4 + pair (64 ints, 2 per lane)
for g in range(4):
    w(f"            for (int e = lane; e < 64; e += 32) {{")
    w(f"                int bk = k0 + e / 4;")
    w(f"                int gc = col0 + {8 * g} + 2 * (e - (e / 4) * 4);")
    w(f"                int lo = 0;")
    w(f"                int hi = 0;")
    w(f"                if (bk < k) {{")
    w(f"                    if (gc < n) {{")
    w(f"                        lo = transB == 0 ? {bits('b', 'offB + bk * n + gc')} : {bits('b', 'offB + gc * k + bk')};")
    w(f"                    }}")
    w(f"                    if (gc + 1 < n) {{")
    w(f"                        hi = transB == 0 ? {bits('b', 'offB + bk * n + gc + 1')} : {bits('b', 'offB + (gc + 1) * k + bk')};")
    w(f"                    }}")
    w(f"                }}")
    w(f"                bt{g}[e] = lo | (hi << 16);")
    w(f"            }}")
w("            kc.localBarrier();")
for i in range(2):
    w(f"            HalfFloat[] fa{i} = kc.mmaLoadA(at{i}, 16);")
for j in range(4):
    w(f"            HalfFloat[] fb{j} = kc.mmaLoadB(bt{j}, 16);")
for i in range(2):
    for j in range(4):
        w(f"            acc{i}{j} = kc.{MMA}(fa{i}, fb{j}, acc{i}{j}, MMAShape.M16N8K16);")
w("            kc.localBarrier();")
w("        }")
w("        int lr = lane / 4;")
w("        int lc = 2 * (lane - lr * 4);")
for i in range(2):
    for j in range(4):
        w(f"        storeAt(c, bias, offC, m, n, row0 + {16 * i} + lr, col0 + {8 * j} + lc, acc{i}{j}[0], epilogue);")
        w(f"        storeAt(c, bias, offC, m, n, row0 + {16 * i} + lr, col0 + {8 * j} + lc + 1, acc{i}{j}[1], epilogue);")
        w(f"        storeAt(c, bias, offC, m, n, row0 + {16 * i} + lr + 8, col0 + {8 * j} + lc, acc{i}{j}[2], epilogue);")
        w(f"        storeAt(c, bias, offC, m, n, row0 + {16 * i} + lr + 8, col0 + {8 * j} + lc + 1, acc{i}{j}[3], epilogue);")
w("    }")
print("\n".join(o))
