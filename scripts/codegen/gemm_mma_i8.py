"""Generates MmaInt8Kernels, jitNN's INT8 tensor-core GEMM for CUDA (KernelContext MMA, m16n8k32,
compute capability 8.0+). Prints the Java class.

C[M, N] = sx * sw[n] * (A B^T - (zp - offset) * colsum[n]) + bias[n]: A [M, K] INT8 activations,
B [N, K] INT8 weights (one row per output), INT32 accumulation, and the dequantisation in the
epilogue (sx and zp the activations' scale and zero point, device scalars; the activations are
stored minus offset, 128 for UINT8; sw[n] the weights' per-output scale, colsum[n] the sum of row
n of B). K is padded with zeros to Kp, a multiple of 32.

Operands come packed four bytes to an int: A row-major (int (row, c) holds k = 4c .. 4c + 3, Kp / 4
ints a row), written so by quantize; B packed once into the shared-tile order (packWeights in
Int8), so a K step of a 128-column block is 1024 consecutive ints. A 256-thread block (8 warps,
4 x 2) computes a 128 x 128 tile of C over a range of K steps, the next step's operands loaded into
registers while the current step's MMAs run; warp (wm, wn) owns rows 32 wm .. + 31 and columns
64 wn .. + 63. With several K splits (groupIdz), each writes INT32 partial sums and reduce adds them
and dequantises.

Shared layouts are those the fragment loads read: A as 16 x 32-byte rows, B as 8-column panels of
16 rows of 4 ints (int (kr, jp) holds B(2 kr, j), B(2 kr + 1, j), B(2 kr, j + 1), B(2 kr + 1, j + 1)
for j = 2 jp).
"""
BM, BN, BK = 128, 128, 32
WARPS_M, WARPS_N = 4, 2
FM = BM // WARPS_M // 16   # A fragments per warp (2)
FN = BN // WARPS_N // 8    # B fragments per warp (8)
PER = BM * BK // 4 // 256  # ints of each tile a thread stages per K step (4)

o = []
w = o.append


def ind(n):
    return "    " * n


w("package org.beehive.jitnn.kernels;")
w("")
w("import uk.ac.manchester.tornado.api.KernelContext;")
w("import uk.ac.manchester.tornado.api.enums.MMAShape;")
w("import uk.ac.manchester.tornado.api.types.arrays.FloatArray;")
w("import uk.ac.manchester.tornado.api.types.arrays.IntArray;")
w("")
w("/**")
w(" * INT8 tensor-core GEMM with the dequantisation fused, generated by scripts/codegen/gemm_mma_i8.py:")
w(" * C = sx * sw[n] * (A B^T - (zp - offset) * colsum[n]) + bias[n] for INT8 A [M, K] and B [N, K],")
w(" * packed four to an int (A by {@link #quantize}, B in tile order), INT32 accumulation (m16n8k32,")
w(" * CUDA compute capability 8.0+). Grid: ceil(M / 128) x ceil(N / 128) x splits work-groups of 256")
w(" * threads; with more than one split, {@link #reduce} finishes.")
w(" */")
w("public final class MmaInt8Kernels {")
w("")
w("    /** Output tile edge. */")
w("    public static final int TILE = %d;" % BM)
w("    /** K per step; K is padded to a multiple of it. */")
w("    public static final int STEP = %d;" % BK)
w("    /** Threads per work-group. */")
w("    public static final int THREADS = 256;")
w("")
w("    private MmaInt8Kernels() {")
w("    }")
w("")
w("    public static void gemm(KernelContext ctx, IntArray a, IntArray b, FloatArray c, IntArray partial, int m, int n, int kp, int splits, FloatArray sx, FloatArray zp,")
w("            int offset, FloatArray sw, IntArray colsum, FloatArray bias, int hasBias) {")
i = 2
w(ind(i) + "int tid = ctx.localIdx;")
w(ind(i) + "int lane = tid & 31;")
w(ind(i) + "int warp = tid >> 5;")
w(ind(i) + "int warpM = warp / %d;" % WARPS_N)
w(ind(i) + "int warpN = warp - warpM * %d;" % WARPS_N)
w(ind(i) + "int row0 = ctx.groupIdx * %d;" % BM)
w(ind(i) + "int col0 = ctx.groupIdy * %d;" % BN)
w(ind(i) + "int z = ctx.groupIdz;")
w(ind(i) + "int lda = kp >> 2;")
w(ind(i) + "int steps = kp / %d;" % BK)
w(ind(i) + "int per = (steps + splits - 1) / splits;")
w(ind(i) + "int s0 = z * per;")
w(ind(i) + "int s1 = s0 + per < steps ? s0 + per : steps;")
w(ind(i) + "int bBase = ctx.groupIdy * steps * %d;" % (BN * BK // 4))
w(ind(i) + "int[] aTile = ctx.allocateIntLocalArray(%d);" % (BM * BK // 4))
w(ind(i) + "int[] bTile = ctx.allocateIntLocalArray(%d);" % (BN * BK // 4))
for fm in range(FM):
    for fn in range(FN):
        w(ind(i) + "int[] c%d%d = ctx.mmaFragmentInt(0);" % (fm, fn))
# per-thread staging indices: A int e = row * 8 + c; rows past m read as 0
for p in range(PER):
    w(ind(i) + "int ra%d = row0 + ((tid + %d) >> 3);" % (p, p * 256))
    w(ind(i) + "boolean va%d = ra%d < m;" % (p, p))
    w(ind(i) + "int ga%d = ra%d * lda + ((tid + %d) & 7);" % (p, p, p * 256))
# prologue: stage step s0
w(ind(i) + "if (s0 < s1) {")
for p in range(PER):
    w(ind(i + 1) + "aTile[tid + %d] = va%d ? a.get(ga%d + s0 * 8) : 0;" % (p * 256, p, p))
    w(ind(i + 1) + "bTile[tid + %d] = b.get(bBase + s0 * %d + tid + %d);" % (p * 256, BN * BK // 4, p * 256))
w(ind(i) + "}")
w(ind(i) + "ctx.localBarrier();")
w(ind(i) + "for (int s = s0; s < s1; s++) {")
i = 3
for p in range(PER):
    w(ind(i) + "int na%d = 0;" % p)
    w(ind(i) + "int nb%d = 0;" % p)
w(ind(i) + "if (s + 1 < s1) {")
for p in range(PER):
    w(ind(i + 1) + "na%d = va%d ? a.get(ga%d + (s + 1) * 8) : 0;" % (p, p, p))
    w(ind(i + 1) + "nb%d = b.get(bBase + (s + 1) * %d + tid + %d);" % (p, BN * BK // 4, p * 256))
w(ind(i) + "}")
for fm in range(FM):
    w(ind(i) + "byte[] a%d = ctx.mmaLoadAInt8(aTile, %d, warpM * %d + %d);" % (fm, BK, 32 * 32, fm * 16 * 32))
for fn in range(FN):
    w(ind(i) + "byte[] b%d = ctx.mmaLoadBInt8(bTile, %d, (warpN * %d + %d) * 256);" % (fn, BK, FN, fn))
w(ind(i) + "ctx.localBarrier();")
w(ind(i) + "if (s + 1 < s1) {")
for p in range(PER):
    w(ind(i + 1) + "aTile[tid + %d] = na%d;" % (p * 256, p))
    w(ind(i + 1) + "bTile[tid + %d] = nb%d;" % (p * 256, p))
w(ind(i) + "}")
for fm in range(FM):
    for fn in range(FN):
        w(ind(i) + "c%d%d = ctx.mmaInt8(a%d, b%d, c%d%d, MMAShape.M16N8K32);" % (fm, fn, fm, fn, fm, fn))
w(ind(i) + "ctx.localBarrier();")
i = 2
w(ind(i) + "}")
# epilogue
w(ind(i) + "float scale = sx.get(0);")
w(ind(i) + "int zero = (int) zp.get(0) - offset;")
w(ind(i) + "int rBase = row0 + warpM * 32 + (lane >> 2);")
w(ind(i) + "int cBase = col0 + warpN * 64 + ((lane & 3) << 1);")
w(ind(i) + "int pBase = z * m * n;")
for fn in range(FN):
    for half in range(2):
        w(ind(i) + "{")
        w(ind(i + 1) + "int col = cBase + %d;" % (fn * 8 + half))
        w(ind(i + 1) + "if (col < n) {")
        w(ind(i + 2) + "float f = scale * sw.get(col);")
        w(ind(i + 2) + "int corr = zero * colsum.get(col);")
        w(ind(i + 2) + "float add = hasBias != 0 ? bias.get(col) : 0.0f;")
        for fm in range(FM):
            for rh in range(2):
                e = rh * 2 + half
                r = "r%d%d" % (fm, rh)
                w(ind(i + 2) + "int %s = rBase + %d;" % (r, fm * 16 + rh * 8))
                w(ind(i + 2) + "if (%s < m) {" % r)
                w(ind(i + 3) + "if (splits == 1) {")
                w(ind(i + 4) + "c.set(%s * n + col, f * (c%d%d[%d] - corr) + add);" % (r, fm, fn, e))
                w(ind(i + 3) + "} else {")
                w(ind(i + 4) + "partial.set(pBase + %s * n + col, c%d%d[%d]);" % (r, fm, fn, e))
                w(ind(i + 3) + "}")
                w(ind(i + 2) + "}")
        w(ind(i + 1) + "}")
        w(ind(i) + "}")
w("    }")
w("")
w("    /** Adds the INT32 partial sums of the K splits of {@link #gemm} and dequantises them, one thread per output. */")
w("    public static void reduce(KernelContext ctx, IntArray partial, FloatArray c, int m, int n, int splits, FloatArray sx, FloatArray zp, int offset, FloatArray sw,")
w("            IntArray colsum, FloatArray bias, int hasBias) {")
w("        int id = ctx.globalIdx;")
w("        if (id < m * n) {")
w("            int col = id % n;")
w("            int acc = 0;")
w("            for (int z = 0; z < splits; z++) {")
w("                acc += partial.get(z * m * n + id);")
w("            }")
w("            int zero = (int) zp.get(0) - offset;")
w("            float add = hasBias != 0 ? bias.get(col) : 0.0f;")
w("            c.set(id, sx.get(0) * sw.get(col) * (acc - zero * colsum.get(col)) + add);")
w("        }")
w("    }")
w("")
w("    /**")
w("     * q = clamp(round_half_even(x / scale) + zp, lo, hi) - offset for x [M, K], packed four to an")
w("     * int along rows padded to kp (padding 0): ONNX QuantizeLinear to UINT8 (lo 0, hi 255, offset")
w("     * 128) or INT8 (-128, 127, 0); scale and zp are device scalars. One thread per int.")
w("     */")
w("    public static void quantize(KernelContext ctx, FloatArray x, IntArray q, FloatArray scale, FloatArray zp, float lo, float hi, int offset, int m, int k, int kp) {")
w("        int id = ctx.globalIdx;")
w("        int lda = kp >> 2;")
w("        if (id < m * lda) {")
w("            int row = id / lda;")
w("            int k0 = (id - row * lda) << 2;")
w("            float s = scale.get(0);")
w("            float zero = zp.get(0);")
w("            int packed = 0;")
w("            for (int j = 0; j < 4; j++) {")
w("                int v = 0;")
w("                if (k0 + j < k) {")
w("                    float f = ElementwiseKernels.roundHalfEven(x.get(row * k + k0 + j) / s) + zero;")
w("                    f = f < lo ? lo : (f > hi ? hi : f);")
w("                    v = (int) f - offset;")
w("                }")
w("                packed |= (v & 0xFF) << (j << 3);")
w("            }")
w("            q.set(id, packed);")
w("        }")
w("    }")
w("}")
print("\n".join(o))
