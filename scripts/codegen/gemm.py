"""Generates register-blocked GEMM KernelContext kernels for jitNN (Java has no macros, and
TornadoVM needs the accumulators as scalars). Prints one Java method to stdout.

usage: python gemm.py <name> <BM> <BN> <BK> <TM> <TN> [batched] [f16|bf16]
  BM x BN outputs per work-group of (BN/TN) x (BM/TM) threads, each thread TM x TN outputs
  strided by the thread-grid size (coalesced stores, conflict-free local reads).
  batched: C[z] = op(A[z]) op(B[z]) for z < batch, with batch strides strideA and strideB (0
  broadcasts one matrix) and C contiguous; the batch is folded into the y dimension of the grid
  (groupIdy = z * tilesY + row tile).
  splitk: C_z = op(A) op(B) over K slice z (k from z * ks to min(k, (z + 1) * ks)), written without
  epilogue to the partial buffer c at z * m * n; the slice is folded into the y dimension of the
  grid (groupIdy = z * tilesY + row tile), and a reduction sums the partials (GemmKernels.sumSplitK).
  f16, bf16: A and B in half precision (HalfFloatArray, or bfloat16 bits in a ShortArray),
  converted to FP32 as they are staged in local memory; accumulation and C stay FP32.
  pad: local-memory rows one float longer than the tile (BM + 1, BN + 1), so the tile stores,
  where consecutive threads write consecutive k, fall in different banks.
  dbuf: the next k tile is loaded into registers while the current one is multiplied, then stored
  to local memory after it, so global loads overlap the arithmetic.
"""
import sys

name, BM, BN, BK, TM, TN = sys.argv[1], *map(int, sys.argv[2:7])
FLAGS = sys.argv[7:]
BATCHED = "batched" in FLAGS
SPLITK = "splitk" in FLAGS
assert not (BATCHED and SPLITK)
PAD = 1 if "pad" in FLAGS else 0
DBUF = "dbuf" in FLAGS
IN = "f16" if "f16" in FLAGS else ("bf16" if "bf16" in FLAGS else "f32")
ARR = {"f32": "FloatArray", "f16": "HalfFloatArray", "bf16": "ShortArray"}[IN]


def load(arr, index):
    if IN == "f16":
        return f"{arr}.get({index}).getFloat32()"
    if IN == "bf16":
        return f"LowPrecision.fromBF16({arr}.get({index}))"
    return f"{arr}.get({index})"
OA, OB = ("offA + ", "offB + ") if BATCHED else ("", "")
LX, LY = BN // TN, BM // TM
T = LX * LY
assert (BM * BK) % T == 0 and (BN * BK) % T == 0
QA, QB = BM * BK // T, BN * BK // T
SA, SB = BM + PAD, BN + PAD

o = []
w = o.append
if SPLITK:
    w(f"    /** Split-K register-blocked GEMM, generated by scripts/codegen/gemm.py {name} {BM} {BN} {BK} {TM} {TN} splitk:")
    w(f"     * partial C_z = op(A) op(B) over K slice z of {{@code ks}}, at z * m * n in c. A {LX}x{LY} work-group computes a {BM}x{BN}")
    w(f"     * block. Launch {LX}x{LY} groups of threads over ceil(N/{BN}) x (slices * tilesY) groups, tilesY = ceil(M/{BM}). */")
    w(f"    public static void {name}(KernelContext kc, {ARR} a, {ARR} b, FloatArray c, int m, int n, int k, int transA, int transB, int ks, int tilesY) {{")
elif BATCHED:
    w(f"    /** Batched register-blocked GEMM, generated by scripts/codegen/gemm.py {name} {BM} {BN} {BK} {TM} {TN} batched:")
    w(f"     * C[z] = op(A[z]) op(B[z]) with A[z] at z * strideA, B[z] at z * strideB (0 broadcasts) and C[z] at z * m * n.")
    w(f"     * A {LX}x{LY} work-group computes a {BM}x{BN} block. Launch {LX}x{LY} groups of threads over ceil(N/{BN}) x")
    w(f"     * (batch * tilesY) groups, tilesY = ceil(M/{BM}). {{@code epilogue}}: see {{@link #store}}. */")
    w(f"    public static void {name}(KernelContext kc, {ARR} a, {ARR} b, FloatArray c, FloatArray bias, int m, int n, int k, int transA, int transB, int epilogue, int strideA, int strideB, int tilesY) {{")
else:
    w(f"    /** Register-blocked GEMM, generated by scripts/codegen/gemm.py {name} {BM} {BN} {BK} {TM} {TN}: a {LX}x{LY} work-group")
    w(f"     * computes a {BM}x{BN} block of C, each thread {TM}x{TN} outputs. Launch {LX}x{LY} groups of threads over")
    w(f"     * ceil(N/{BN}) x ceil(M/{BM}) groups. {{@code epilogue}}: see {{@link #store}}. */")
    w(f"    public static void {name}(KernelContext kc, {ARR} a, {ARR} b, FloatArray c, FloatArray bias, int m, int n, int k, int transA, int transB, int epilogue) {{")
w(f"        float[] as = kc.allocateFloatLocalArray({BK * SA});")
w(f"        float[] bs = kc.allocateFloatLocalArray({BK * SB});")
w("        int tx = kc.localIdx;")
w("        int ty = kc.localIdy;")
w(f"        int tid = ty * {LX} + tx;")
if SPLITK:
    w("        int bz = kc.groupIdy / tilesY;")
    w(f"        int row0 = (kc.groupIdy - bz * tilesY) * {BM};")
    w("        int kBegin = bz * ks;")
    w("        int kEnd = kBegin + ks < k ? kBegin + ks : k;")
    w("        int offC = bz * m * n;")
elif BATCHED:
    w("        int bz = kc.groupIdy / tilesY;")
    w(f"        int row0 = (kc.groupIdy - bz * tilesY) * {BM};")
    w("        int offA = bz * strideA;")
    w("        int offB = bz * strideB;")
    w("        int offC = bz * m * n;")
else:
    w(f"        int row0 = kc.groupIdy * {BM};")
w(f"        int col0 = kc.groupIdx * {BN};")
for i in range(TM):
    for j in range(TN):
        w(f"        float c{i}_{j} = 0.0f;")
if SPLITK:
    w(f"        int tiles = (kEnd - kBegin + {BK - 1}) / {BK};")
else:
    w(f"        int tiles = (k + {BK - 1}) / {BK};")
KLIM = "kEnd" if SPLITK else "k"


def tile_loads_loop(k0, ind):
    """Loads the tile at k0 straight into local memory, one loop per operand."""
    w(f"{ind}for (int q = 0; q < {QA}; q++) {{")
    w(f"{ind}    int idx = tid + {T} * q;")
    w(f"{ind}    int mm;")
    w(f"{ind}    int kk;")
    w(f"{ind}    if (transA == 0) {{")
    w(f"{ind}        mm = idx / {BK};")
    w(f"{ind}        kk = idx - mm * {BK};")
    w(f"{ind}    }} else {{")
    w(f"{ind}        kk = idx / {BM};")
    w(f"{ind}        mm = idx - kk * {BM};")
    w(f"{ind}    }}")
    w(f"{ind}    int gr = row0 + mm;")
    w(f"{ind}    int gk = {k0} + kk;")
    w(f"{ind}    float va = 0.0f;")
    w(f"{ind}    if ((gr < m) & (gk < {KLIM})) {{")
    w(f"{ind}        va = transA == 0 ? {load('a', OA + 'gr * k + gk')} : {load('a', OA + 'gk * m + gr')};")
    w(f"{ind}    }}")
    w(f"{ind}    as[kk * {SA} + mm] = va;")
    w(f"{ind}}}")
    w(f"{ind}for (int q = 0; q < {QB}; q++) {{")
    w(f"{ind}    int idx = tid + {T} * q;")
    w(f"{ind}    int nn;")
    w(f"{ind}    int kb;")
    w(f"{ind}    if (transB == 0) {{")
    w(f"{ind}        kb = idx / {BN};")
    w(f"{ind}        nn = idx - kb * {BN};")
    w(f"{ind}    }} else {{")
    w(f"{ind}        nn = idx / {BK};")
    w(f"{ind}        kb = idx - nn * {BK};")
    w(f"{ind}    }}")
    w(f"{ind}    int gc = col0 + nn;")
    w(f"{ind}    int gkb = {k0} + kb;")
    w(f"{ind}    float vb = 0.0f;")
    w(f"{ind}    if ((gkb < {KLIM}) & (gc < n)) {{")
    w(f"{ind}        vb = transB == 0 ? {load('b', OB + 'gkb * n + gc')} : {load('b', OB + 'gc * k + gkb')};")
    w(f"{ind}    }}")
    w(f"{ind}    bs[kb * {SB} + nn] = vb;")
    w(f"{ind}}}")


def tile_loads(dst, k0, ind):
    """Loads the A and B elements of the tile at k0 into the prefetch registers (unrolled)."""
    for q in range(QA):
        w(f"{ind}{{")
        w(f"{ind}    int idx = tid + {T * q};")
        w(f"{ind}    int mm;")
        w(f"{ind}    int kk;")
        w(f"{ind}    if (transA == 0) {{")
        w(f"{ind}        mm = idx / {BK};")
        w(f"{ind}        kk = idx - mm * {BK};")
        w(f"{ind}    }} else {{")
        w(f"{ind}        kk = idx / {BM};")
        w(f"{ind}        mm = idx - kk * {BM};")
        w(f"{ind}    }}")
        w(f"{ind}    int gr = row0 + mm;")
        w(f"{ind}    int gk = {k0} + kk;")
        w(f"{ind}    float va = 0.0f;")
        w(f"{ind}    if ((gr < m) & (gk < {KLIM})) {{")
        w(f"{ind}        va = transA == 0 ? {load('a', OA + 'gr * k + gk')} : {load('a', OA + 'gk * m + gr')};")
        w(f"{ind}    }}")
        w(f"{ind}    {'as[kk * ' + str(SA) + ' + mm]' if dst is None else 'ra' + str(q)} = va;")
        w(f"{ind}}}")
    for q in range(QB):
        w(f"{ind}{{")
        w(f"{ind}    int idx = tid + {T * q};")
        w(f"{ind}    int nn;")
        w(f"{ind}    int kb;")
        w(f"{ind}    if (transB == 0) {{")
        w(f"{ind}        kb = idx / {BN};")
        w(f"{ind}        nn = idx - kb * {BN};")
        w(f"{ind}    }} else {{")
        w(f"{ind}        nn = idx / {BK};")
        w(f"{ind}        kb = idx - nn * {BK};")
        w(f"{ind}    }}")
        w(f"{ind}    int gc = col0 + nn;")
        w(f"{ind}    int gkb = {k0} + kb;")
        w(f"{ind}    float vb = 0.0f;")
        w(f"{ind}    if ((gkb < {KLIM}) & (gc < n)) {{")
        w(f"{ind}        vb = transB == 0 ? {load('b', OB + 'gkb * n + gc')} : {load('b', OB + 'gc * k + gkb')};")
        w(f"{ind}    }}")
        w(f"{ind}    {'bs[kb * ' + str(SB) + ' + nn]' if dst is None else 'rb' + str(q)} = vb;")
        w(f"{ind}}}")


def store_registers(ind):
    """Stores the prefetched registers of tile k0 into local memory (same index mapping as the loads)."""
    for q in range(QA):
        w(f"{ind}{{")
        w(f"{ind}    int idx = tid + {T * q};")
        w(f"{ind}    int mm;")
        w(f"{ind}    int kk;")
        w(f"{ind}    if (transA == 0) {{")
        w(f"{ind}        mm = idx / {BK};")
        w(f"{ind}        kk = idx - mm * {BK};")
        w(f"{ind}    }} else {{")
        w(f"{ind}        kk = idx / {BM};")
        w(f"{ind}        mm = idx - kk * {BM};")
        w(f"{ind}    }}")
        w(f"{ind}    as[kk * {SA} + mm] = ra{q};")
        w(f"{ind}}}")
    for q in range(QB):
        w(f"{ind}{{")
        w(f"{ind}    int idx = tid + {T * q};")
        w(f"{ind}    int nn;")
        w(f"{ind}    int kb;")
        w(f"{ind}    if (transB == 0) {{")
        w(f"{ind}        kb = idx / {BN};")
        w(f"{ind}        nn = idx - kb * {BN};")
        w(f"{ind}    }} else {{")
        w(f"{ind}        nn = idx / {BK};")
        w(f"{ind}        kb = idx - nn * {BK};")
        w(f"{ind}    }}")
        w(f"{ind}    bs[kb * {SB} + nn] = rb{q};")
        w(f"{ind}}}")


if DBUF:
    for q in range(QA):
        w(f"        float ra{q} = 0.0f;")
    for q in range(QB):
        w(f"        float rb{q} = 0.0f;")
    # registers hold tile 0 before the loop; each iteration stores tile t, then prefetches t + 1
    w("        int kStart = " + ("kBegin" if SPLITK else "0") + ";")
    w("        if (tiles > 0) {")
    tile_loads("reg", "kStart", "            ")
    w("        }")
    w("        for (int t = 0; t < tiles; t++) {")
    store_registers("            ")
    w("            kc.localBarrier();")
    w("            if (t + 1 < tiles) {")
    tile_loads("reg", f"kStart + (t + 1) * {BK}", "                ")
    w("            }")
else:
    w("        for (int t = 0; t < tiles; t++) {")
    w(f"            int k0 = {'kBegin + ' if SPLITK else ''}t * {BK};")
    tile_loads_loop("k0", "            ")
w("            kc.localBarrier();")
w(f"            for (int p = 0; p < {BK}; p++) {{")
for i in range(TM):
    w(f"                float a{i} = as[p * {SA} + ty + {LY * i}];")
for j in range(TN):
    w(f"                float b{j} = bs[p * {SB} + tx + {LX * j}];")
for i in range(TM):
    for j in range(TN):
        w(f"                c{i}_{j} += a{i} * b{j};")
w("            }")
w("            kc.localBarrier();")
w("        }")
w("        int r = row0 + ty;")
w("        int q = col0 + tx;")
for i in range(TM):
    for j in range(TN):
        if SPLITK:
            w(f"        storeAt(c, c, offC, m, n, r + {LY * i}, q + {LX * j}, c{i}_{j}, 0);")
        elif BATCHED:
            w(f"        storeAt(c, bias, offC, m, n, r + {LY * i}, q + {LX * j}, c{i}_{j}, epilogue);")
        else:
            w(f"        store(c, bias, m, n, r + {LY * i}, q + {LX * j}, c{i}_{j}, epilogue);")
w("    }")
print("\n".join(o))
