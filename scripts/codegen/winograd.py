# Lavin and Gray's matrices for the points 0, 1, -1, 2, -2 and infinity.
from fractions import Fraction as Fr
import struct

BT4 = [[4, 0, -5, 0, 1, 0], [0, -4, -4, 1, 1, 0], [0, 4, -4, -1, 1, 0], [0, -2, -1, 2, 1, 0], [0, 2, -1, -2, 1, 0], [0, 4, 0, -5, 0, 1]]
G4 = [[Fr(1, 4), 0, 0], [Fr(-1, 6), Fr(-1, 6), Fr(-1, 6)], [Fr(-1, 6), Fr(1, 6), Fr(-1, 6)], [Fr(1, 24), Fr(1, 12), Fr(1, 6)], [Fr(1, 24), Fr(-1, 12), Fr(1, 6)], [0, 0, 1]]
AT4 = [[1, 1, 1, 1, 1, 0], [0, 1, -1, 2, -2, 0], [0, 1, 1, 4, 4, 0], [0, 1, -1, 8, -8, 1]]


def lit(c):
    f = struct.unpack("f", struct.pack("f", float(c)))[0]
    return repr(f) + "f"


def combo(coefs, names):
    """sum c * name over the non-zero coefficients, as Java."""
    out = ""
    for c, n in zip(coefs, names):
        c = Fr(c)
        if c == 0:
            continue
        if c == 1:
            term, sign = n, "+"
        elif c == -1:
            term, sign = n, "-"
        else:
            term, sign = f"{lit(abs(c))} * {n}", "+" if c > 0 else "-"
        out += (f" {sign} " if out else ("" if sign == "+" else "-")) + term
    return out or "0.0f"


def left(M, src, dst, w, pad, cols):
    """dst[i][j] = sum_k M[i][k] src[k][j], declared as floats dst{i}_{j}."""
    for j in range(cols):
        for i in range(len(M)):
            w(f"{pad}float {dst}{i}_{j} = {combo(M[i], [f'{src}{k}_{j}' for k in range(len(M[i]))])};")


def right(M, src, dst, w, pad, rows):
    """dst[i][j] = sum_k src[i][k] M[j][k] (src times M^T)."""
    for i in range(rows):
        for j in range(len(M)):
            w(f"{pad}float {dst}{i}_{j} = {combo(M[j], [f'{src}{i}_{k}' for k in range(len(M[j]))])};")


