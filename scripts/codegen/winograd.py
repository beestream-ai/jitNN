"""Generates the Winograd F(2x2, 3x3) transform kernels of jitNN's 3x3 stride-1 convolutions
(TornadoVM needs the 4x4 tiles as scalars). Prints three Java methods:

  winogradInput    V[e, c, p] = (B^T d B)[e] for the 4x4 input patch d of tile p of channel c
  winogradWeight   U[e, co, ci] = (G g G^T)[e] for the 3x3 filter g (optionally flipped and
                   transposed, for the gradient of the input)
  winogradOutput   out[n, co, 2 ty + i, 2 tx + j] = (A^T m A)[i, j] for m[e] = M[e, co, p]
  winogradGradOut  D[e, co, p] = (A y A^T)[e] for the 2x2 output-gradient tile y of tile p
  winogradGradWeight dw[co, ci] = G^T u G for u[e] = dU[e, co, ci] (the filter gradient)

with e = 4 row + col of the 4x4 transformed tile, tiles p = (n, ty, tx) over ceil(OH / 2) x
ceil(OW / 2) per image, and M[e] = U[e] V[e] computed between them by one batched GEMM. For the
filter gradient, dU[e] = D[e] V[e]^T is the batched GEMM, over the tiles.
"""


def ind(n):
    return " " * n


def btd(src, dst, w, pad):
    """dst = B^T src B for 4x4 scalars src{i}{j}."""
    for j in range(4):
        w(f"{pad}float t0{j} = {src}0{j} - {src}2{j};")
        w(f"{pad}float t1{j} = {src}1{j} + {src}2{j};")
        w(f"{pad}float t2{j} = {src}2{j} - {src}1{j};")
        w(f"{pad}float t3{j} = {src}1{j} - {src}3{j};")
    for i in range(4):
        w(f"{pad}float {dst}{i}0 = t{i}0 - t{i}2;")
        w(f"{pad}float {dst}{i}1 = t{i}1 + t{i}2;")
        w(f"{pad}float {dst}{i}2 = t{i}2 - t{i}1;")
        w(f"{pad}float {dst}{i}3 = t{i}1 - t{i}3;")


