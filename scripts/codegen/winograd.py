"""Generates the Winograd F(2x2, 3x3) transform kernels of jitNN's 3x3 stride-1 convolutions
(TornadoVM needs the 4x4 tiles as scalars). Prints three Java methods:

  winogradInput    V[e, c, p] = (B^T d B)[e] for the 4x4 input patch d of tile p of channel c
  winogradWeight   U[e, co, ci] = (G g G^T)[e] for the 3x3 filter g (optionally flipped and
                   transposed, for the gradient of the input)
  winogradOutput   out[n, co, 2 ty + i, 2 tx + j] = (A^T m A)[i, j] for m[e] = M[e, co, p]
  winogradGradOut  D[e, co, p] = (A y A^T)[e] for the 2x2 output-gradient tile y of tile p
  winogradGradWeight dw[co, ci] = G^T u G for u[e] = dU[e, co, ci] (the filter gradient)

with e = 4 row + col of the 4x4 transformed tile, tiles p = (n, ty, tx) over ceil(OH / 2) x
ceil(OW / 2) per image, and M[e] = U[e] V[e] computed between them by one batched GEMM. For the
filter gradient, dU[e] = D[e] V[e]^T is the batched GEMM, over the tiles.
"""


def ind(n):
    return " " * n


def btd(src, dst, w, pad):
    """dst = B^T src B for 4x4 scalars src{i}{j}."""
    for j in range(4):
        w(f"{pad}float t0{j} = {src}0{j} - {src}2{j};")
        w(f"{pad}float t1{j} = {src}1{j} + {src}2{j};")
        w(f"{pad}float t2{j} = {src}2{j} - {src}1{j};")
        w(f"{pad}float t3{j} = {src}1{j} - {src}3{j};")
    for i in range(4):
        w(f"{pad}float {dst}{i}0 = t{i}0 - t{i}2;")
        w(f"{pad}float {dst}{i}1 = t{i}1 + t{i}2;")
        w(f"{pad}float {dst}{i}2 = t{i}2 - t{i}1;")
        w(f"{pad}float {dst}{i}3 = t{i}1 - t{i}3;")


o = []
w = o.append

# ---------------------------------------------------------------- input
w("    /**")
w("     * Winograd F(2x2, 3x3) input transform, generated by scripts/codegen/winograd.py: (B^T d B)[e] for the 4x4")
w("     * patch d at rows 2 ty - pad .., columns 2 tx - pad .. of channel ci of image n, tile p = (n * th + ty) * tw")
w("     * + tx (zero outside the image and for p >= tiles), at V[((e * slices + s) * c + ci) * chunk + p - s * chunk]")
w("     * with s = p / chunk: the tiles cut into slices of chunk (slices = 1, chunk = tiles: V[e, ci, p]). One")
w("     * thread per (ci, p < slices * chunk).")
w("     */")
w("    public static void winogradInput(KernelContext kc, FloatArray x, FloatArray v, int c, int h, int wd, int pad, int th, int tw, int tiles, int slices, int chunk) {")
w("        int idx = kc.globalIdx;")
w("        int span = slices * chunk;")
w("        if (idx < c * span) {")
w("            int ci = idx / span;")
w("            int p = idx - ci * span;")
w("            int sl = p / chunk;")
w("            int dst = (sl * c + ci) * chunk + p - sl * chunk;")
w("            int tx = p % tw;")
w("            int r = p / tw;")
w("            int ty = r % th;")
w("            int n = r / th;")
w("            int r0 = 2 * ty - pad;")
w("            int c0 = 2 * tx - pad;")
w("            int base = (n * c + ci) * h * wd;")
for i in range(4):
    for j in range(4):
        w(f"            float d{i}{j} = 0.0f;")
        w(f"            if ((p < tiles) & (r0 + {i} >= 0) & (r0 + {i} < h) & (c0 + {j} >= 0) & (c0 + {j} < wd)) {{")
        w(f"                d{i}{j} = x.get(base + (r0 + {i}) * wd + c0 + {j});")
        w("            }")
btd("d", "v", w, ind(12))
w("            int stride = slices * c * chunk;")
for i in range(4):
    for j in range(4):
        w(f"            v.set({4 * i + j} * stride + dst, v{i}{j});")
w("        }")
w("    }")
w("")

# ---------------------------------------------------------------- weight
w("    /**")
w("     * Winograd F(2x2, 3x3) filter transform, generated by scripts/codegen/winograd.py: U[(e * rows + r) *")
w("     * cols + q] = (G g G^T)[e] with g = w[r, q] (w [rows, cols, 3, 3]), or, with flip = 1, g = the")
w("     * filter w[q, r] rotated by 180 degrees (w [cols, rows, 3, 3]): the filter of the input gradient.")
w("     * One thread per (r, q).")
w("     */")
w("    public static void winogradWeight(KernelContext kc, FloatArray wt, FloatArray u, int rows, int cols, int flip) {")
w("        int idx = kc.globalIdx;")
w("        if (idx < rows * cols) {")
w("            int r = idx / cols;")
w("            int q = idx - r * cols;")
for i in range(3):
    for j in range(3):
        w(f"            float g{i}{j};")
w("            if (flip == 0) {")
w("                int base = (r * cols + q) * 9;")
for i in range(3):
    for j in range(3):
        w(f"                g{i}{j} = wt.get(base + {3 * i + j});")
w("            } else {")
w("                int base = (q * rows + r) * 9;")
for i in range(3):
    for j in range(3):
        w(f"                g{i}{j} = wt.get(base + {3 * (2 - i) + (2 - j)});")
w("            }")
# t = G g (4x3)
for j in range(3):
    w(f"            float t0{j} = g0{j};")
    w(f"            float t1{j} = 0.5f * (g0{j} + g1{j} + g2{j});")
    w(f"            float t2{j} = 0.5f * (g0{j} - g1{j} + g2{j});")
    w(f"            float t3{j} = g2{j};")
w("            int stride = rows * cols;")
for i in range(4):
    vals = [f"t{i}0", f"0.5f * (t{i}0 + t{i}1 + t{i}2)", f"0.5f * (t{i}0 - t{i}1 + t{i}2)", f"t{i}2"]
    for j in range(4):
        w(f"            u.set({4 * i + j} * stride + idx, {vals[j]});")
w("        }")
w("    }")
w("")

# ---------------------------------------------------------------- output
w("    /**")
w("     * Winograd F(2x2, 3x3) output transform, generated by scripts/codegen/winograd.py: the 2x2 outputs")
w("     * (A^T m A) of tile p of channel co, m[e] = M[(e * c + co) * tiles + p], with the bias/ReLU")
w("     * epilogue of {@link #conv2dForward}. One thread per (co, p).")
w("     */")
w("    public static void winogradOutput(KernelContext kc, FloatArray mm, FloatArray out, FloatArray bias, int c, int oh, int ow, int th, int tw, int tiles, int epilogue) {")
w("        int idx = kc.globalIdx;")
w("        if (idx < c * tiles) {")
w("            int co = idx / tiles;")
w("            int p = idx - co * tiles;")
w("            int tx = p % tw;")
w("            int r = p / tw;")
w("            int ty = r % th;")
w("            int n = r / th;")
w("            int stride = c * tiles;")
for i in range(4):
    for j in range(4):
        w(f"            float m{i}{j} = mm.get({4 * i + j} * stride + idx);")
for j in range(4):
    w(f"            float t0{j} = m0{j} + m1{j} + m2{j};")
    w(f"            float t1{j} = m1{j} - m2{j} - m3{j};")
w("            float b = 0.0f;")
w("            if ((epilogue & 1) != 0) {")
w("                b = bias.get(co);")
w("            }")
w("            int base = (n * c + co) * oh * ow;")
for i in range(2):
    for j, e in enumerate([f"t{i}0 + t{i}1 + t{i}2", f"t{i}1 - t{i}2 - t{i}3"]):
        w(f"            float y{i}{j} = {e} + b;")
        w("            if ((epilogue & 2) != 0) {")
        w(f"                y{i}{j} = y{i}{j} > 0.0f ? y{i}{j} : 0.0f;")
        w("            }")
        w(f"            if ((2 * ty + {i} < oh) & (2 * tx + {j} < ow)) {{")
        w(f"                out.set(base + (2 * ty + {i}) * ow + 2 * tx + {j}, y{i}{j});")
        w("            }")
w("        }")
w("    }")

# ---------------------------------------------------------------- output gradient
w("")
w("    /**")
w("     * Winograd F(2x2, 3x3) transform of the output gradient, generated by scripts/codegen/winograd.py:")
w("     * (A y A^T)[e] for the 2x2 tile y of dy at rows 2 ty .., columns 2 tx .. of channel co (zero outside the")
w("     * output and for p >= tiles), sliced as in {@link #winogradInput}. One thread per (co, p < slices * chunk).")
w("     */")
w("    public static void winogradGradOut(KernelContext kc, FloatArray dy, FloatArray d, int c, int oh, int ow, int th, int tw, int tiles, int slices, int chunk) {")
w("        int idx = kc.globalIdx;")
w("        int span = slices * chunk;")
w("        if (idx < c * span) {")
w("            int co = idx / span;")
w("            int p = idx - co * span;")
w("            int sl = p / chunk;")
w("            int dst = (sl * c + co) * chunk + p - sl * chunk;")
w("            int tx = p % tw;")
w("            int r = p / tw;")
w("            int ty = r % th;")
w("            int n = r / th;")
w("            int base = (n * c + co) * oh * ow;")
for i in range(2):
    for j in range(2):
        w(f"            float y{i}{j} = 0.0f;")
        w(f"            if ((p < tiles) & (2 * ty + {i} < oh) & (2 * tx + {j} < ow)) {{")
        w(f"                y{i}{j} = dy.get(base + (2 * ty + {i}) * ow + 2 * tx + {j});")
        w("            }")
# t = A y (4x2), rows of A: [1,0],[1,1],[1,-1],[0,-1]
for j in range(2):
    w(f"            float t0{j} = y0{j};")
    w(f"            float t1{j} = y0{j} + y1{j};")
    w(f"            float t2{j} = y0{j} - y1{j};")
    w(f"            float t3{j} = -y1{j};")
w("            int stride = slices * c * chunk;")
for i in range(4):
    vals = [f"t{i}0", f"t{i}0 + t{i}1", f"t{i}0 - t{i}1", f"-t{i}1"]
    for j in range(4):
        w(f"            d.set({4 * i + j} * stride + dst, {vals[j]});")
w("        }")
w("    }")

# ---------------------------------------------------------------- filter gradient
w("")
w("    /**")
w("     * Winograd F(2x2, 3x3) filter-gradient transform, generated by scripts/codegen/winograd.py: dw[(co * cin")
w("     * + ci) * 9 ..] = G^T u G for u[e] = the sum over the slices s of du[((e * slices + s) * cout + co) * cin + ci]")
w("     * (in slice order). One thread per (co, ci).")
w("     */")
w("    public static void winogradGradWeight(KernelContext kc, FloatArray du, FloatArray dw, int cout, int cin, int slices) {")
w("        int idx = kc.globalIdx;")
w("        if (idx < cout * cin) {")
w("            int plane = cout * cin;")
for i in range(4):
    for j in range(4):
        w(f"            float u{i}{j} = 0.0f;")
w("            for (int sl = 0; sl < slices; sl++) {")
for i in range(4):
    for j in range(4):
        w(f"                u{i}{j} += du.get(({4 * i + j} * slices + sl) * plane + idx);")
w("            }")
# t = G^T u (3x4)
for j in range(4):
    w(f"            float t0{j} = u0{j} + 0.5f * (u1{j} + u2{j});")
    w(f"            float t1{j} = 0.5f * (u1{j} - u2{j});")
    w(f"            float t2{j} = 0.5f * (u1{j} + u2{j}) + u3{j};")
for i in range(3):
    vals = [f"t{i}0 + 0.5f * (t{i}1 + t{i}2)", f"0.5f * (t{i}1 - t{i}2)", f"0.5f * (t{i}1 + t{i}2) + t{i}3"]
    for j in range(3):
        w(f"            dw.set(idx * 9 + {3 * i + j}, {vals[j]});")
w("        }")
w("    }")

print("    // ---------------------------------------------------------------- Winograd F(2x2, 3x3)")
print()
print("\n".join(o))
