"""Generates jitNN's Metal GEMM on simdgroup 8x8 matrix units (KernelContext.simdgroupMatrix*).

A work-group of 4 SIMD groups (128 threads) computes a 64x64 block of C; SIMD group (sr, sc)
owns rows 32*sr.. and columns 32*sc.. as a 4x4 grid of 8x8 accumulators. A and B are staged in
local memory as As[64][16] and Bs[16][64]. Fragment stores are unguarded inside a fragment, so
the kernel needs M and N to be multiples of 8 (K is arbitrary: out-of-range loads are zero).
"""
import sys

BK = int(sys.argv[1]) if len(sys.argv) > 1 else 16
NAME = sys.argv[2] if len(sys.argv) > 2 else "gemmSimdgroup"
IN = sys.argv[3] if len(sys.argv) > 3 else "f32"   # f16 or bf16: half-precision A and B, converted on load
ARR = {"f32": "FloatArray", "f16": "HalfFloatArray", "bf16": "ShortArray"}[IN]


def load(arr, index):
    if IN == "f16":
        return f"{arr}.get({index}).getFloat32()"
    if IN == "bf16":
        return f"LowPrecision.fromBF16({arr}.get({index}))"
    return f"{arr}.get({index})"
Q = 64 * BK // 128
o = []
w = o.append
w("    /**")
w("     * Metal GEMM on simdgroup 8x8 matrix units (generated by scripts/codegen/gemm_simdgroup.py). A")
w("     * 128-thread work-group computes a 64x64 block of C; each of its four SIMD groups a 32x32")
w("     * sub-block as 16 hardware accumulators. Needs m and n to be multiples of 8. Launch 128-thread")
w("     * groups over ceil(n/64) x ceil(m/64) blocks (1-D, block = groupIdx).")
w("     */")
w(f"    public static void {NAME}(KernelContext kc, {ARR} a, {ARR} b, FloatArray c, int m, int n, int k, int transA, int transB) {{")
w(f"        float[] as = kc.allocateFloatLocalArray({64 * BK});")
w(f"        float[] bs = kc.allocateFloatLocalArray({64 * BK});")
w("        int tid = kc.localIdx;")
w("        int blocksX = (n + 63) / 64;")
w("        int row0 = (kc.groupIdx / blocksX) * 64;")
w("        int col0 = (kc.groupIdx % blocksX) * 64;")
w("        int sg = tid / 32;")
w("        int sr = (sg / 2) * 32;")
w("        int sc = (sg % 2) * 32;")
for i in range(4):
    for j in range(4):
        w(f"        Matrix8x8Float acc{i}{j} = kc.simdgroupMatrixZero();")
w(f"        for (int k0 = 0; k0 < k; k0 += {BK}) {{")
w(f"            for (int q = 0; q < {Q}; q++) {{")
w("                int idx = tid + 128 * q;")
w("                int mm;")
w("                int kk;")
w("                if (transA == 0) {")
w(f"                    mm = idx / {BK};")
w(f"                    kk = idx - mm * {BK};")
w("                } else {")
w("                    kk = idx / 64;")
w("                    mm = idx - kk * 64;")
w("                }")
w("                int gr = row0 + mm;")
w("                int gk = k0 + kk;")
w("                float va = 0.0f;")
w("                if ((gr < m) & (gk < k)) {")
w(f"                    va = transA == 0 ? {load('a', 'gr * k + gk')} : {load('a', 'gk * m + gr')};")
w("                }")
w(f"                as[mm * {BK} + kk] = va;")
w("                int nn;")
w("                int kb;")
w("                if (transB == 0) {")
w("                    kb = idx / 64;")
w("                    nn = idx - kb * 64;")
w("                } else {")
w(f"                    nn = idx / {BK};")
w(f"                    kb = idx - nn * {BK};")
w("                }")
w("                int gc = col0 + nn;")
w("                int gkb = k0 + kb;")
w("                float vb = 0.0f;")
w("                if ((gkb < k) & (gc < n)) {")
w(f"                    vb = transB == 0 ? {load('b', 'gkb * n + gc')} : {load('b', 'gc * k + gkb')};")
w("                }")
w("                bs[kb * 64 + nn] = vb;")
w("            }")
w("            kc.localBarrier();")
w(f"            for (int p = 0; p < {BK}; p += 8) {{")
for i in range(4):
    w(f"                Matrix8x8Float a{i} = kc.simdgroupMatrixLoad(as, (sr + {8 * i}) * {BK} + p, {BK});")
for j in range(4):
    w(f"                Matrix8x8Float b{j} = kc.simdgroupMatrixLoad(bs, p * 64 + sc + {8 * j}, 64);")
for i in range(4):
    for j in range(4):
        w(f"                acc{i}{j} = kc.simdgroupMatrixMultiplyAccumulate(a{i}, b{j}, acc{i}{j});")
w("            }")
w("            kc.localBarrier();")
w("        }")
for i in range(4):
    for j in range(4):
        w(f"        if ((row0 + sr + {8 * i} < m) & (col0 + sc + {8 * j} < n)) {{")
        w(f"            kc.simdgroupMatrixStore(acc{i}{j}, c, (row0 + sr + {8 * i}) * n + col0 + sc + {8 * j}, n);")
        w("        }")
w("    }")
print("\n".join(o))
