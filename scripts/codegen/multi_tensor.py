"""Generates jitNN's multi-tensor kernels (MultiTensorKernels.java): optimiser updates and gradient
statistics over several tensors in one launch, as PyTorch's foreach kernels. A kernel cannot pick
an array at run time, so every slot is its own branch. TornadoVM tasks take at most 20 arguments,
which sets the slots per launch: 4 tensors for the optimisers (p, g and state arrays each), 8
gradients for the statistics.

usage: python multi_tensor.py > MultiTensorKernels.java
"""
OPT = 4
STATS = 8

o = []
w = o.append
w("""package org.beehive.jitnn.kernels;

import uk.ac.manchester.tornado.api.KernelContext;
import uk.ac.manchester.tornado.api.math.TornadoMath;
import uk.ac.manchester.tornado.api.types.arrays.FloatArray;
import uk.ac.manchester.tornado.api.types.arrays.IntArray;

/**
 * Multi-tensor kernels, generated by scripts/codegen/multi_tensor.py: the optimiser updates of up
 * to 4 parameters, and the gradient statistics of up to 8 gradients, in one launch each. Thread i
 * of an update belongs to the slot whose range [start, start + sizes[slot]) holds it; unused
 * slots have size 0. {@code stats} = [norm, factor, skip] as in {@link LowPrecision#gradStats}.
 */
public final class MultiTensorKernels {

    /** Tensors per optimiser launch. */
    public static final int OPT_SLOTS = 4;
    /** Gradients per statistics launch (one work-group each). */
    public static final int STATS_SLOTS = 8;
    private static final int GROUP = 256;

    private MultiTensorKernels() {
    }

    private static void adamAt(FloatArray p, FloatArray g, FloatArray m, FloatArray v, FloatArray hyper, float factor, int i) {
        float lr = hyper.get(0);
        float b1 = hyper.get(1);
        float b2 = hyper.get(2);
        float wd = hyper.get(6);
        float w = p.get(i);
        float grad = g.get(i) * factor;
        if (hyper.get(7) != 0.0f) {
            w = w - lr * wd * w;
        } else {
            grad = grad + wd * w;
        }
        float mi = b1 * m.get(i) + (1.0f - b1) * grad;
        float vi = b2 * v.get(i) + (1.0f - b2) * grad * grad;
        m.set(i, mi);
        v.set(i, vi);
        p.set(i, w - lr * (mi / hyper.get(4)) / (TornadoMath.sqrt(vi / hyper.get(5)) + hyper.get(3)));
    }

    private static void sgdAt(FloatArray p, FloatArray g, FloatArray hyper, float factor, int i) {
        float w = p.get(i);
        p.set(i, w - hyper.get(0) * (g.get(i) * factor + hyper.get(2) * w));
    }

    private static void momentumAt(FloatArray p, FloatArray g, FloatArray buf, FloatArray hyper, float factor, int i) {
        float w = p.get(i);
        float mu = hyper.get(1);
        float grad = g.get(i) * factor + hyper.get(2) * w;
        float v = mu * buf.get(i) + grad;
        buf.set(i, v);
        float step = hyper.get(3) != 0.0f ? grad + mu * v : v;
        p.set(i, w - hyper.get(0) * step);
    }
""")


def kernel(name, doc, arrays, call):
    params = ", ".join(f"FloatArray {a}{k}" for k in range(OPT) for a in arrays)
    w(f"    /** {doc} */")
    w(f"    public static void {name}(KernelContext kc, {params}, FloatArray hyper, FloatArray stats, IntArray sizes) {{")
    w("        int i = kc.globalIdx;")
    w("        if (stats.get(2) == 0.0f) {")
    w("            float factor = stats.get(1);")
    for k in range(OPT):
        w(f"            int s{k} = {'0' if k == 0 else f's{k - 1} + sizes.get({k - 1})'};")
    for k in range(OPT):
        kw = "if" if k == 0 else "} else if"
        w(f"            {kw} ((i >= s{k}) & (i < s{k} + sizes.get({k}))) {{")
        w(f"                {call(k)};")
    w("            }")
    w("        }")
    w("    }")
    w("")


kernel("adam", "Adam, or AdamW when hyper[7] != 0, over 4 parameters; hyper = [lr, beta1, beta2, eps, 1 - beta1^t, 1 - beta2^t, weightDecay, decoupled].", ["p", "g", "m", "v"],
       lambda k: f"adamAt(p{k}, g{k}, m{k}, v{k}, hyper, factor, i - s{k})")
kernel("sgd", "SGD over 4 parameters; hyper = [lr, momentum, weightDecay, nesterov].", ["p", "g"],
       lambda k: f"sgdAt(p{k}, g{k}, hyper, factor, i - s{k})")
kernel("sgdMomentum", "SGD with (optionally Nesterov) momentum, dampening 0, over 4 parameters; hyper as sgd.", ["p", "g", "b"],
       lambda k: f"momentumAt(p{k}, g{k}, b{k}, hyper, factor, i - s{k})")

# gradient statistics: work-group k reduces gradient k (reductions written out: Metal cannot pass a
# local array to a helper method, J12)
params = ", ".join(f"FloatArray g{k}" for k in range(STATS))
w("    /**")
w("     * Sum of squares and a NaN/infinity flag of up to 8 gradients: work-group k writes")
w("     * partial[2 (slot0 + k)] and partial[2 (slot0 + k) + 1]. Launch 8 groups of 256 threads.")
w("     */")
w(f"    public static void sumSquaresFinite(KernelContext kc, {params}, FloatArray partial, IntArray sizes, int slot0) {{")
w("        float[] sq = kc.allocateFloatLocalArray(GROUP);")
w("        int[] bad = kc.allocateIntLocalArray(GROUP);")
w("        int l = kc.localIdx;")
w("        int k = kc.groupIdx;")
w("        int n = sizes.get(k);")
w("        float s = 0.0f;")
w("        int b = 0;")
for k in range(STATS):
    kw = "if" if k == 0 else "} else if"
    w(f"        {kw} (k == {k}) {{")
    w(f"            for (int i = l; i < n; i += GROUP) {{")
    w(f"                float x = g{k}.get(i);")
    w(f"                s += x * x;")
    w(f"                b = b | LowPrecision.nonFinite(x);")
    w(f"            }}")
w("        }")
w("""        sq[l] = s;
        bad[l] = b;
        kc.localBarrier();
        for (int r = GROUP / 2; r > 0; r = r / 2) {
            if (l < r) {
                sq[l] = sq[l] + sq[l + r];
                bad[l] = bad[l] | bad[l + r];
            }
            kc.localBarrier();
        }
        if ((l == 0) & (n > 0)) {
            partial.set(2 * (slot0 + k), sq[0]);
            partial.set(2 * (slot0 + k) + 1, bad[0]);
        }
    }
}""")
print("\n".join(o))
