package ai.beestream.jitnn.kernels;

import uk.ac.manchester.tornado.api.KernelContext;
import uk.ac.manchester.tornado.api.math.TornadoMath;
import uk.ac.manchester.tornado.api.types.arrays.FloatArray;
import uk.ac.manchester.tornado.api.types.arrays.IntArray;

/**
 * Fused scaled dot-product attention for head dimensions up to 128, generated by
 * scripts/codegen/flash.py 128. FlashAttention's tiling with an online softmax: scores and
 * probabilities are never stored. Z = batch * heads attention problems of T queries and S keys
 * with head dimension d; q, k, v and o are addressed through strides, so they can live in any
 * layout (separate [B, H, T, d] tensors, [B, T, H, d], or one packed [B, T, 3, H, d] projection),
 * and the gradients dq, dk, dv use the layouts of q, k and v. The row logsumexp lse is [Z, T].
 * meta = [heads, mb, mh, mt, ms, then (offset, batch, head, token) strides of q, k, v and o]: the
 * first five read the additive mask (strides over batch, head, query and key; 0 for broadcast
 * dimensions). Masking may also be causal (query i sees keys 0 .. i). Work-groups of 256 threads = 2 rows x 128 columns; thread (row,
 * column) keeps one output element in a register. Tiles of 16 rows stream through local memory.
 */
public final class FlashKernels128 {

    public static final int D = 128;
    public static final int THREADS = 256;
    /** Query rows (forward, dQ) or key rows (dK, dV) per work-group. */
    public static final int ROWS = 2;
    public static final int TILE = 16;
    private static final int PAD = 129;
    /** Scores at or below this are masked out (exp gives exactly 0). */
    private static final float MASKED = -3.0e38f;

    private FlashKernels128() {
    }

    /** Index of row {@code row} of problem z in operand {@code which} (0 q, 1 k, 2 v, 3 o). */
    private static int at(IntArray meta, int which, int z, int row) {
        int b = z / meta.get(0);
        int h = z - b * meta.get(0);
        int m = 5 + 4 * which;
        return meta.get(m) + b * meta.get(m + 1) + h * meta.get(m + 2) + row * meta.get(m + 3);
    }

    private static float maskValue(FloatArray mask, IntArray meta, int z, int i, int j) {
        int b = z / meta.get(0);
        int h = z - b * meta.get(0);
        return mask.get(b * meta.get(1) + h * meta.get(2) + i * meta.get(3) + j * meta.get(4));
    }

    /** Forward: o and lse. Z * ceil(T / ROWS) work-groups of THREADS threads. */
    public static void forward(KernelContext kc, FloatArray q, FloatArray k, FloatArray v, FloatArray mask, FloatArray o, FloatArray lse, int t, int s, int d,
            float scale, int causal, int hasMask, IntArray meta) {
        float[] qs = kc.allocateFloatLocalArray(ROWS * PAD);
        float[] ks = kc.allocateFloatLocalArray(TILE * PAD);
        float[] vs = kc.allocateFloatLocalArray(TILE * PAD);
        float[] sc = kc.allocateFloatLocalArray(ROWS * TILE);
        int tid = kc.localIdx;
        int row = tid / D;
        int col = tid - row * D;
        int qBlocks = (t + ROWS - 1) / ROWS;
        int z = kc.groupIdx / qBlocks;
        int q0 = (kc.groupIdx - z * qBlocks) * ROWS;
        int i = q0 + row;
        for (int e = tid; e < ROWS * D; e += THREADS) {
            int r = e / D;
            int c = e - r * D;
            float x = 0.0f;
            if ((q0 + r < t) & (c < d)) {
                x = q.get(at(meta, 0, z, q0 + r) + c);
            }
            qs[r * PAD + c] = x;
        }
        float acc = 0.0f;
        float m = MASKED;
        float sum = 0.0f;
        int kEnd = s;
        if (causal != 0) {
            int last = q0 + ROWS;
            kEnd = last < s ? last : s;
        }
        for (int j0 = 0; j0 < kEnd; j0 += TILE) {
            for (int e = tid; e < TILE * D; e += THREADS) {
                int r = e / D;
                int c = e - r * D;
                int j = j0 + r;
                float kv = 0.0f;
                float vv = 0.0f;
                if ((j < s) & (c < d)) {
                    kv = k.get(at(meta, 1, z, j) + c);
                    vv = v.get(at(meta, 2, z, j) + c);
                }
                ks[r * PAD + c] = kv;
                vs[r * PAD + c] = vv;
            }
            kc.localBarrier();
            for (int e = tid; e < ROWS * TILE; e += THREADS) {
                int r = e / TILE;
                int jj = e - r * TILE;
                int qi = q0 + r;
                int j = j0 + jj;
                float sv = MASKED;
                if ((qi < t) & (j < s) & ((causal == 0) | (j <= qi))) {
                    float dot = 0.0f;
                    for (int c = 0; c < d; c++) {
                        dot += qs[r * PAD + c] * ks[jj * PAD + c];
                    }
                    sv = dot * scale;
                    if (hasMask != 0) {
                        sv += maskValue(mask, meta, z, qi, j);
                    }
                }
                sc[r * TILE + jj] = sv;
            }
            kc.localBarrier();
            float tileMax = MASKED;
            for (int jj = 0; jj < TILE; jj++) {
                float sv = sc[row * TILE + jj];
                tileMax = sv > tileMax ? sv : tileMax;
            }
            float mNew = tileMax > m ? tileMax : m;
            float alpha = m > MASKED ? TornadoMath.exp(m - mNew) : 0.0f;
            sum = sum * alpha;
            acc = acc * alpha;
            for (int jj = 0; jj < TILE; jj++) {
                float sv = sc[row * TILE + jj];
                float p = sv > MASKED ? TornadoMath.exp(sv - mNew) : 0.0f;
                sum += p;
                acc += p * vs[jj * PAD + col];
            }
            m = mNew;
            kc.localBarrier();
        }
        if ((i < t) & (col < d)) {
            o.set(at(meta, 3, z, i) + col, sum > 0.0f ? acc / sum : 0.0f);
        }
        if ((i < t) & (col == 0)) {
            lse.set(z * t + i, sum > 0.0f ? m + TornadoMath.log(sum) : MASKED);
        }
    }


    /** dQ: ds = p (dO . v - delta) with p = exp(s - lse), dQ += scale * ds * k. Grid as forward. */
    public static void backwardQ(KernelContext kc, FloatArray q, FloatArray k, FloatArray v, FloatArray mask, FloatArray dout, FloatArray lse, FloatArray delta,
            FloatArray dq, int t, int s, int d, float scale, int causal, int hasMask, IntArray meta) {
        float[] qs = kc.allocateFloatLocalArray(ROWS * PAD);
        float[] os = kc.allocateFloatLocalArray(ROWS * PAD);
        float[] ks = kc.allocateFloatLocalArray(TILE * PAD);
        float[] vs = kc.allocateFloatLocalArray(TILE * PAD);
        float[] dsc = kc.allocateFloatLocalArray(ROWS * TILE);
        int tid = kc.localIdx;
        int row = tid / D;
        int col = tid - row * D;
        int qBlocks = (t + ROWS - 1) / ROWS;
        int z = kc.groupIdx / qBlocks;
        int q0 = (kc.groupIdx - z * qBlocks) * ROWS;
        int i = q0 + row;
        for (int e = tid; e < ROWS * D; e += THREADS) {
            int r = e / D;
            int c = e - r * D;
            float x = 0.0f;
            float y = 0.0f;
            if ((q0 + r < t) & (c < d)) {
                x = q.get(at(meta, 0, z, q0 + r) + c);
                y = dout.get(at(meta, 3, z, q0 + r) + c);
            }
            qs[r * PAD + c] = x;
            os[r * PAD + c] = y;
        }
        float acc = 0.0f;
        int kEnd = s;
        if (causal != 0) {
            int last = q0 + ROWS;
            kEnd = last < s ? last : s;
        }
        for (int j0 = 0; j0 < kEnd; j0 += TILE) {
            for (int e = tid; e < TILE * D; e += THREADS) {
                int r = e / D;
                int c = e - r * D;
                int j = j0 + r;
                float kv = 0.0f;
                float vv = 0.0f;
                if ((j < s) & (c < d)) {
                    kv = k.get(at(meta, 1, z, j) + c);
                    vv = v.get(at(meta, 2, z, j) + c);
                }
                ks[r * PAD + c] = kv;
                vs[r * PAD + c] = vv;
            }
            kc.localBarrier();
            for (int e = tid; e < ROWS * TILE; e += THREADS) {
                int r = e / TILE;
                int jj = e - r * TILE;
                int qi = q0 + r;
                int j = j0 + jj;
                float g = 0.0f;
                if ((qi < t) & (j < s) & ((causal == 0) | (j <= qi))) {
                    float li = lse.get(z * t + qi);
                    float dot = 0.0f;
                    float dp = 0.0f;
                    for (int c = 0; c < d; c++) {
                        dot += qs[r * PAD + c] * ks[jj * PAD + c];
                        dp += os[r * PAD + c] * vs[jj * PAD + c];
                    }
                    float sv = dot * scale;
                    if (hasMask != 0) {
                        sv += maskValue(mask, meta, z, qi, j);
                    }
                    float p = li > MASKED ? TornadoMath.exp(sv - li) : 0.0f;
                    g = p * (dp - delta.get(z * t + qi)) * scale;
                }
                dsc[r * TILE + jj] = g;
            }
            kc.localBarrier();
            for (int jj = 0; jj < TILE; jj++) {
                acc += dsc[row * TILE + jj] * ks[jj * PAD + col];
            }
            kc.localBarrier();
        }
        if ((i < t) & (col < d)) {
            dq.set(at(meta, 0, z, i) + col, acc);
        }
    }

    /**
     * dK and dV: over the queries that see key j, dV += p * dO and dK += scale * ds * q.
     * Z * ceil(S / ROWS) work-groups of THREADS threads; query and dO tiles staged in local memory.
     */
    public static void backwardKV(KernelContext kc, FloatArray q, FloatArray k, FloatArray v, FloatArray mask, FloatArray dout, FloatArray lse, FloatArray delta,
            FloatArray dk, FloatArray dv, int t, int s, int d, float scale, int causal, int hasMask, IntArray meta) {
        float[] kcache = kc.allocateFloatLocalArray(ROWS * PAD);
        float[] vcache = kc.allocateFloatLocalArray(ROWS * PAD);
        float[] qs = kc.allocateFloatLocalArray(TILE * PAD);
        float[] os = kc.allocateFloatLocalArray(TILE * PAD);
        float[] ps = kc.allocateFloatLocalArray(ROWS * TILE);
        float[] gs = kc.allocateFloatLocalArray(ROWS * TILE);
        int tid = kc.localIdx;
        int row = tid / D;
        int col = tid - row * D;
        int kBlocks = (s + ROWS - 1) / ROWS;
        int z = kc.groupIdx / kBlocks;
        int k0 = (kc.groupIdx - z * kBlocks) * ROWS;
        int j = k0 + row;
        for (int e = tid; e < ROWS * D; e += THREADS) {
            int r = e / D;
            int c = e - r * D;
            float x = 0.0f;
            float y = 0.0f;
            if ((k0 + r < s) & (c < d)) {
                x = k.get(at(meta, 1, z, k0 + r) + c);
                y = v.get(at(meta, 2, z, k0 + r) + c);
            }
            kcache[r * PAD + c] = x;
            vcache[r * PAD + c] = y;
        }
        float accK = 0.0f;
        float accV = 0.0f;
        int iStart = 0;
        if (causal != 0) {
            iStart = k0 / TILE * TILE;
        }
        for (int i0 = iStart; i0 < t; i0 += TILE) {
            for (int e = tid; e < TILE * D; e += THREADS) {
                int r = e / D;
                int c = e - r * D;
                int qi = i0 + r;
                float x = 0.0f;
                float y = 0.0f;
                if ((qi < t) & (c < d)) {
                    x = q.get(at(meta, 0, z, qi) + c);
                    y = dout.get(at(meta, 3, z, qi) + c);
                }
                qs[r * PAD + c] = x;
                os[r * PAD + c] = y;
            }
            kc.localBarrier();
            for (int e = tid; e < ROWS * TILE; e += THREADS) {
                int r = e / TILE;
                int ii = e - r * TILE;
                int kj = k0 + r;
                int qi = i0 + ii;
                float p = 0.0f;
                float g = 0.0f;
                if ((kj < s) & (qi < t) & ((causal == 0) | (kj <= qi))) {
                    float li = lse.get(z * t + qi);
                    float dot = 0.0f;
                    float dp = 0.0f;
                    for (int c = 0; c < d; c++) {
                        dot += qs[ii * PAD + c] * kcache[r * PAD + c];
                        dp += os[ii * PAD + c] * vcache[r * PAD + c];
                    }
                    float sv = dot * scale;
                    if (hasMask != 0) {
                        sv += maskValue(mask, meta, z, qi, kj);
                    }
                    p = li > MASKED ? TornadoMath.exp(sv - li) : 0.0f;
                    g = p * (dp - delta.get(z * t + qi)) * scale;
                }
                ps[r * TILE + ii] = p;
                gs[r * TILE + ii] = g;
            }
            kc.localBarrier();
            for (int ii = 0; ii < TILE; ii++) {
                accV += ps[row * TILE + ii] * os[ii * PAD + col];
                accK += gs[row * TILE + ii] * qs[ii * PAD + col];
            }
            kc.localBarrier();
        }
        if ((j < s) & (col < d)) {
            dk.set(at(meta, 1, z, j) + col, accK);
            dv.set(at(meta, 2, z, j) + col, accV);
        }
    }
}
